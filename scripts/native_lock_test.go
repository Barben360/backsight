// fakeLockDocker prints the image's listing from listing.txt and
// fakeLockUV's pip compile writes body.txt to its -o file and keeps its -c
// file as constraints.txt and its input (the last argument) as in.txt; each logs its argv to calls.
const fakeLockDocker = `#!/bin/sh
d=$(dirname "$0")
printf 'docker %s\n' "$*" >> "$d/calls"
cat "$d/listing.txt"
`

const fakeLockUV = `#!/bin/sh
d=$(dirname "$0")
printf 'uv %s\n' "$*" >> "$d/calls"
o= c=
for a; do in=$a; done
cp "$in" "$d/in.txt"
while [ $# -gt 0 ]; do
  [ "$1" = -o ] && o=$2
  [ "$1" = -c ] && c=$2
  shift
done
cp "$c" "$d/constraints.txt"
cat "$d/body.txt" > "$o"
`

// imageListing is the image's python3 --version and site-packages, with
// hindsight-api-slim at hs.
func imageListing(hs string) string {
	return "Python 3.11.17\n__pycache__\n_editable_impl_hindsight_api_slim.pth\nhindsight_api_slim-" + hs +
		".dist-info\npg0\npg0_embedded-0.15.2.dist-info\ntorch-2.13.0+cpu.dist-info\nZope.Interface-7.0.dist-info\n"
}

const lockBody = `hindsight-api-slim==1.1.0 \
    --hash=sha256:1111111111111111111111111111111111111111111111111111111111111111
pg0-embedded==0.15.2 \
    --hash=sha256:2222222222222222222222222222222222222222222222222222222222222222
zope-interface==7.0 \
    --hash=sha256:3333333333333333333333333333333333333333333333333333333333333333
`

// lastFake is the fakes' directory of the last runNativeLock.
var lastFake string

// runNativeLock runs scripts/native-lock.sh with the fakes first on PATH
// and the lock at lock; it returns the fakes' calls, the output and the
// exit error.
func runNativeLock(t *testing.T, listing, body, lock string, args ...string) (calls, out string, err error) {
	calls, out, _, err = runNativeLockIn(t, listing, body, lock, args...)
	return calls, out, err
}

// runNativeLockIn is runNativeLock that also returns the constraints the
// compile was given.
func runNativeLockIn(t *testing.T, listing, body, lock string, args ...string) (calls, out, constraints string, err error) {
	t.Helper()
	return runNativeLockOv(t, "", listing, body, lock, args...)
}

// runNativeLockOv is runNativeLockIn with overrides as the overrides file
// (NATIVE_LOCK_OVERRIDES; the others run with an empty one, not the
// committed overrides.txt).
func runNativeLockOv(t *testing.T, overrides, listing, body, lock string, args ...string) (calls, out, constraints string, err error) {
	t.Helper()
	root, _ := filepath.Abs("..")
	fake := t.TempDir()
	lastFake = fake
	for name, content := range map[string]string{"docker": fakeLockDocker, "uv": fakeLockUV, "listing.txt": listing, "body.txt": body, "overrides.txt": overrides} {
		if werr := os.WriteFile(filepath.Join(fake, name), []byte(content), 0o755); werr != nil {
			t.Fatal(werr)
		}
	}
	cmd := exec.Command(filepath.Join(root, "scripts", "native-lock.sh"), args...)
	cmd.Env = append(os.Environ(), "PATH="+fake+":"+os.Getenv("PATH"), "NATIVE_LOCK="+lock, "NATIVE_LOCK_OVERRIDES="+filepath.Join(fake, "overrides.txt"))
	var b bytes.Buffer
	cmd.Stdout, cmd.Stderr = &b, &b
	err = cmd.Run()
	c, _ := os.ReadFile(filepath.Join(fake, "calls"))
	cons, _ := os.ReadFile(filepath.Join(fake, "constraints.txt"))
	return string(c), b.String(), string(cons), err
}

func TestNativeLockScriptChecksThePin(t *testing.T) {
	testtool.SkipWindows(t, "linux-only: POSIX script")
	pin := pinnedImage(t) // render.go's
	tag := strings.Split(pin, "@")[0]
	tag = tag[strings.LastIndex(tag, ":")+1:]
	lockBody := strings.ReplaceAll(lockBody, "hindsight-api-slim==1.1.0", "hindsight-api-slim=="+tag)
	lockHeader := "# Generated by scripts/native-lock.sh: do not edit.\n# image: " + pin +
		"\n# python: 3.11.17 (image: 3.11.17)\n# platform: x86_64-manylinux_2_28\n"
	t.Run("an image shipping another hindsight than its tag", func(t *testing.T) {
		lock := filepath.Join(t.TempDir(), "lock.txt")
		_ = os.WriteFile(lock, []byte(lockHeader+lockBody), 0o644)
		calls, out, err := runNativeLock(t, imageListing("9.9.9"), lockBody, lock, "--check")
		if err == nil {
			t.Fatalf("--check passed:\n%s", out)
		}
		if !strings.Contains(out, tag) || !strings.Contains(out, "9.9.9") {
			t.Errorf("the refusal names not both versions:\n%s", out)
		}
		if !strings.Contains(calls, "docker run --rm --entrypoint sh "+pin+" -c ") {
			t.Errorf("the image read is not render.go's pin:\n%s", calls)
		}
	})

	t.Run("writes the lock with its header", func(t *testing.T) {
		lock := filepath.Join(t.TempDir(), "lock.txt")
		calls, out, err := runNativeLock(t, imageListing(tag), lockBody, lock)
		if err != nil {
			t.Fatalf("%v:\n%s", err, out)
		}
		in, _ := os.ReadFile(filepath.Join(lastFake, "in.txt"))
		if want := "hindsight-api-slim[local-onnx,embedded-db]==" + tag + "\npg0-embedded==0.15.2\n"; string(in) != want {
			t.Errorf("compiled %q, want %q", in, want)
		}
		got, _ := os.ReadFile(lock)
		if string(got) != lockHeader+lockBody {
			t.Errorf("lock:\n%s\nwant:\n%s", got, lockHeader+lockBody)
		}
		for _, want := range []string{"uv pip compile ", "--generate-hashes", "--python-version 3.11 ", "--python-platform x86_64-manylinux_2_28"} {
			if !strings.Contains(calls, want) {
				t.Errorf("uv pip compile lacks %q:\n%s", want, calls)
			}
		}
	})

	t.Run("--check passes on the same versions, other hashes", func(t *testing.T) {
		lock := filepath.Join(t.TempDir(), "lock.txt")
		committed := lockHeader + strings.ReplaceAll(lockBody, "1111", "9999")
		_ = os.WriteFile(lock, []byte(committed), 0o644)
		if _, out, err := runNativeLock(t, imageListing(tag), lockBody, lock, "--check"); err != nil {
			t.Fatalf("%v:\n%s", err, out)
		}
		if got, _ := os.ReadFile(lock); string(got) != committed {
			t.Error("--check rewrote the lock")
		}
	})

	t.Run("--check fails on another version", func(t *testing.T) {
		lock := filepath.Join(t.TempDir(), "lock.txt")
		_ = os.WriteFile(lock, []byte(lockHeader+strings.Replace(lockBody, "zope-interface==7.0", "zope-interface==6.4", 1)), 0o644)
		_, out, err := runNativeLock(t, imageListing(tag), lockBody, lock, "--check")
		if err == nil || !strings.Contains(out, "zope-interface==6.4") || !strings.Contains(out, "zope-interface==7.0") {
			t.Errorf("--check = %v:\n%s", err, out)
		}
	})

	t.Run("a resolved package missing from the image", func(t *testing.T) {
		lock := filepath.Join(t.TempDir(), "lock.txt")
		body := lockBody + "extra-pkg==1.0 \\\n    --hash=sha256:4444444444444444444444444444444444444444444444444444444444444444\n"
		_, out, err := runNativeLock(t, imageListing(tag), body, lock)
		if err == nil || !strings.Contains(out, "extra-pkg==1.0") {
			t.Errorf("= %v:\n%s", err, out)
		}
		if _, serr := os.Stat(lock); serr == nil {
			t.Error("a lock was written")
		}
	})

	t.Run("the constraints are the image's set without torch", func(t *testing.T) {
		lock := filepath.Join(t.TempDir(), "lock.txt")
		_, out, cons, err := runNativeLockIn(t, imageListing(tag), lockBody, lock)
		if err != nil {
			t.Fatalf("%v:\n%s", err, out)
		}
		if want := "hindsight-api-slim==" + tag + "\npg0-embedded==0.15.2\nzope-interface==7.0\n"; cons != want {
			t.Errorf("constraints:\n%s\nwant:\n%s", cons, want)
		}
	})

	// overrides.txt: a version in place of the image's, or a package the
	// image lacks, each with its reason, recorded in the header.
	const overrides = "# why\n\nZope.Interface==7.1: a security fix\nnew-dep==2.0: required by zope-interface 7.1\n"
	overBody := strings.Replace(lockBody, "zope-interface==7.0", "zope-interface==7.1", 1) +
		"new-dep==2.0 \\\n    --hash=sha256:5555555555555555555555555555555555555555555555555555555555555555\n"
	overHeader := lockHeader + "# override: new-dep==2.0 (image: none)\n# override: zope-interface==7.1 (image: 7.0)\n"

	t.Run("an override replaces the image's version and is recorded", func(t *testing.T) {
		lock := filepath.Join(t.TempDir(), "lock.txt")
		_, out, cons, err := runNativeLockOv(t, overrides, imageListing(tag), overBody, lock)
		if err != nil {
			t.Fatalf("%v:\n%s", err, out)
		}
		if want := "hindsight-api-slim==" + tag + "\nnew-dep==2.0\npg0-embedded==0.15.2\nzope-interface==7.1\n"; cons != want {
			t.Errorf("constraints:\n%s\nwant:\n%s", cons, want)
		}
		if got, _ := os.ReadFile(lock); string(got) != overHeader+overBody {
			t.Errorf("lock:\n%s\nwant:\n%s", got, overHeader+overBody)
		}
	})

	// --check compares the header across machines: its order is bytes',
	// not the locale's (en_US puts zope-interface before zope-interface-x,
	// C after).
	t.Run("the override lines are in byte order whatever the locale", func(t *testing.T) {
		requireCollatingLocale(t, "en_US.UTF-8")
		t.Setenv("LC_ALL", "en_US.UTF-8")
		lock := filepath.Join(t.TempDir(), "lock.txt")
		body := overBody + "zope-interface-x==1.0 \\\n    --hash=sha256:6666666666666666666666666666666666666666666666666666666666666666\n"
		_, out, _, err := runNativeLockOv(t, overrides+"zope-interface-x==1.0: required by zope-interface 7.1\n", imageListing(tag), body, lock)
		if err != nil {
			t.Fatalf("%v:\n%s", err, out)
		}
		want := lockHeader + "# override: new-dep==2.0 (image: none)\n# override: zope-interface-x==1.0 (image: none)\n# override: zope-interface==7.1 (image: 7.0)\n"
		if got, _ := os.ReadFile(lock); string(got) != want+body {
			t.Errorf("lock:\n%s\nwant:\n%s", got, want+body)
		}
	})

	t.Run("--check fails on a lock that does not record an override", func(t *testing.T) {
		lock := filepath.Join(t.TempDir(), "lock.txt")
		_ = os.WriteFile(lock, []byte(lockHeader+overBody), 0o644)
		_, out, _, err := runNativeLockOv(t, overrides, imageListing(tag), overBody, lock, "--check")
		if err == nil || !strings.Contains(out, "# override: zope-interface==7.1 (image: 7.0)") {
			t.Errorf("--check = %v:\n%s", err, out)
		}
		_ = os.WriteFile(lock, []byte(overHeader+overBody), 0o644)
		if _, out, _, err := runNativeLockOv(t, overrides, imageListing(tag), overBody, lock, "--check"); err != nil {
			t.Errorf("--check on the recorded lock: %v:\n%s", err, out)
		}
	})

	t.Run("--check fails on a lock without a declared override", func(t *testing.T) {
		lock := filepath.Join(t.TempDir(), "lock.txt")
		_ = os.WriteFile(lock, []byte(lockHeader+lockBody), 0o644)
		_, out, _, err := runNativeLockOv(t, overrides, imageListing(tag), overBody, lock, "--check")
		if err == nil || !strings.Contains(out, "zope-interface==7.1") {
			t.Errorf("--check = %v:\n%s", err, out)
		}
	})

	hash := func(c string) string { return " \\\n    --hash=sha256:" + strings.Repeat(c, 64) + "\n" }
	t.Run("an override of a release the image ships as a pre-release is kept", func(t *testing.T) {
		lock := filepath.Join(t.TempDir(), "lock.txt")
		body := lockBody + "rc-pkg==1.0" + hash("7")
		_, out, _, err := runNativeLockOv(t, "rc-pkg==1.0: the release after the image's 1.0rc1\n", imageListing(tag)+"rc_pkg-1.0rc1.dist-info\n", body, lock)
		if err != nil {
			t.Fatalf("1.0 over the image's 1.0rc1 refused (PEP 440: 1.0rc1 < 1.0): %v:\n%s", err, out)
		}
		if got, _ := os.ReadFile(lock); !strings.Contains(string(got), "# override: rc-pkg==1.0 (image: 1.0rc1)\n") {
			t.Errorf("lock:\n%s", got)
		}
	})

	for name, tc := range map[string]struct{ overrides, listing, body, want string }{
		"a pre-release override of the release the image ships": {"pre-pkg==0.66b1: stale\n", "pre_pkg-0.66.dist-info\n", lockBody + "pre-pkg==0.66b1" + hash("8"), "the image ships pre-pkg 0.66, not older than its override 0.66b1"},
		"a .dev override of the release the image ships":        {"pre-pkg==0.66.dev1: stale\n", "pre_pkg-0.66.dist-info\n", lockBody + "pre-pkg==0.66.dev1" + hash("8"), "the image ships pre-pkg 0.66, not older"},
		"an override the PEP 440 reader cannot compare":         {"zope-interface==7.1+local: x\n", "", overBody, "cannot compare zope-interface's override 7.1+local with the image's 7.0"},
		"a name given twice at two versions":                    {"x-pkg==1.0: a\nX_Pkg==1.1: b\n", "", lockBody, "x-pkg twice"},
		"an empty reason":                                       {"zope-interface==7.1: \n", "", overBody, "name==version: reason"},
		"a line without a name":                                 {"==7.1: why\n", "", overBody, "name==version: reason"},
		"a resolution that does not hold a declared override":   {overrides, "", strings.Replace(overBody, "zope-interface==7.1", "zope-interface==7.0", 1), "does not hold the override(s) zope-interface==7.1"},
		"an override nothing requires":                          {overrides, "", lockBody, "does not hold the override(s) new-dep==2.0 zope-interface==7.1"},
		"an override at the image's own version":                {"zope-interface==7.0: stale\n", "", lockBody, "the image ships zope-interface 7.0"},
		"an override older than the image's version":            {"zope-interface==6.9: stale\n", "", lockBody, "the image ships zope-interface 7.0"},
		"an override without a reason":                          {"zope-interface==7.1\n", "", overBody, "name==version: reason"},
		"an override given twice":                               {"zope-interface==7.1: a\nzope.interface==7.1: b\n", "", overBody, "zope-interface twice"},
		"a resolved version that is neither image nor override": {"new-dep==2.0: x\n", "", overBody, "not the image's or an override: zope-interface==7.1"},
	} {
		t.Run(name+" is refused and nothing is written", func(t *testing.T) {
			lock := filepath.Join(t.TempDir(), "lock.txt")
			_, out, _, err := runNativeLockOv(t, tc.overrides, imageListing(tag)+tc.listing, tc.body, lock)
			if err == nil || !strings.Contains(out, tc.want) {
				t.Errorf("= %v, want a refusal naming %q:\n%s", err, tc.want, out)
			}
			if _, serr := os.Stat(lock); serr == nil {
				t.Error("a lock was written")
			}
		})
	}
}

// runWindowsLock runs native-lock.sh --platform windows with fake uv (and a
// docker that fails: the Windows lock never needs it), the Linux lock at
// linux and the Windows one at win.
func runWindowsLock(t *testing.T, body, linux, win string, args ...string) (out string, err error) {
	t.Helper()
	root, _ := filepath.Abs("..")
	fake := t.TempDir()
	lastFake = fake
	for name, content := range map[string]string{"docker": "#!/bin/sh\necho docker must not run >&2\nexit 9\n", "uv": fakeLockUV, "body.txt": body} {
		if werr := os.WriteFile(filepath.Join(fake, name), []byte(content), 0o755); werr != nil {
			t.Fatal(werr)
		}
	}
	cmd := exec.Command(filepath.Join(root, "scripts", "native-lock.sh"), append([]string{"--platform", "windows"}, args...)...)
	cmd.Env = append(os.Environ(), "PATH="+fake+":"+os.Getenv("PATH"), "NATIVE_LOCK_LINUX="+linux, "NATIVE_LOCK="+win)
	var b bytes.Buffer
	cmd.Stdout, cmd.Stderr = &b, &b
	err = cmd.Run()
	return b.String(), err
}

func TestNativeLockScriptWindows(t *testing.T) {
	testtool.SkipWindows(t, "linux-only: POSIX script")
	const linuxHeader = "# Generated by scripts/native-lock.sh: do not edit.\n# image: ghcr.io/vectorize-io/hindsight:1.1.0@sha256:abc\n" +
		"# python: 3.11.17 (image: 3.11.17)\n# platform: x86_64-manylinux_2_28\n"
	hash := func(c string) string { return " \\\n    --hash=sha256:" + strings.Repeat(c, 64) + "\n" }
	linuxBody := "hindsight-api-slim==1.1.0" + hash("1") + "pg0-embedded==0.15.2" + hash("2") + "onnxruntime==1.31.0" + hash("3") + "Zope.Interface==7.0" + hash("4")
	winBody := "hindsight-api-slim==1.1.0" + hash("5") + "pg0-embedded==0.15.2" + hash("6") + "onnxruntime==1.31.0" + hash("7") +
		"zope-interface==7.0" + hash("8") + "msvc-runtime==14.44.35112" + hash("9") + "winloop==0.8.1" + hash("a")
	linux := filepath.Join(t.TempDir(), "linux.txt")
	if err := os.WriteFile(linux, []byte(linuxHeader+linuxBody), 0o644); err != nil {
		t.Fatal(err)
	}
	sum := sha256.Sum256([]byte(linuxHeader + linuxBody))
	wantHeader := "# Generated by scripts/native-lock.sh --platform windows: do not edit.\n" +
		"# image: ghcr.io/vectorize-io/hindsight:1.1.0@sha256:abc\n# python: 3.11.17 (image: 3.11.17)\n" +
		"# platform: x86_64-pc-windows-msvc\n# linux-lock: " + hex.EncodeToString(sum[:])[:12] + "\n"

	t.Run("writes the Windows lock under the Linux lock's constraints", func(t *testing.T) {
		win := filepath.Join(t.TempDir(), "win.txt")
		out, err := runWindowsLock(t, winBody, linux, win)
		if err != nil {
			t.Fatalf("%v:\n%s", err, out)
		}
		got, _ := os.ReadFile(win)
		if string(got) != wantHeader+winBody {
			t.Errorf("lock:\n%s\nwant:\n%s", got, wantHeader+winBody)
		}
		cons, _ := os.ReadFile(filepath.Join(lastFake, "constraints.txt"))
		if want := "hindsight-api-slim==1.1.0\nonnxruntime==1.31.0\npg0-embedded==0.15.2\nzope-interface==7.0\n"; string(cons) != want {
			t.Errorf("constraints:\n%s\nwant:\n%s", cons, want)
		}
		in, _ := os.ReadFile(filepath.Join(lastFake, "in.txt"))
		if want := "hindsight-api-slim[local-onnx,embedded-db]==1.1.0\npg0-embedded==0.15.2\nmsvc-runtime==14.44.35112\n"; string(in) != want {
			t.Errorf("roots %q, want %q", in, want)
		}
		calls, _ := os.ReadFile(filepath.Join(lastFake, "calls"))
		for _, want := range []string{"--python-platform x86_64-pc-windows-msvc", "--python-version 3.11 ", "--generate-hashes", "--override "} {
			if !strings.Contains(string(calls), want) {
				t.Errorf("uv pip compile lacks %q:\n%s", want, calls)
			}
		}
	})

	t.Run("the Linux lock's overrides are recorded in the Windows header", func(t *testing.T) {
		const rec = "# override: zope-interface==7.0 (image: 6.9)\n"
		linuxOv := filepath.Join(t.TempDir(), "linux.txt")
		if err := os.WriteFile(linuxOv, []byte(linuxHeader+rec+linuxBody), 0o644); err != nil {
			t.Fatal(err)
		}
		ovSum := sha256.Sum256([]byte(linuxHeader + rec + linuxBody))
		want := strings.Replace(wantHeader, hex.EncodeToString(sum[:])[:12], hex.EncodeToString(ovSum[:])[:12], 1) + rec
		win := filepath.Join(t.TempDir(), "win.txt")
		if out, err := runWindowsLock(t, winBody, linuxOv, win); err != nil {
			t.Fatalf("%v:\n%s", err, out)
		}
		if got, _ := os.ReadFile(win); string(got) != want+winBody {
			t.Errorf("lock:\n%s\nwant:\n%s", got, want+winBody)
		}
		_ = os.WriteFile(win, []byte(wantHeader+winBody), 0o644)
		if out, err := runWindowsLock(t, winBody, linuxOv, win, "--check"); err == nil || !strings.Contains(out, strings.TrimSpace(rec)) {
			t.Errorf("--check on a Windows lock without the override line = %v:\n%s", err, out)
		}
	})

	t.Run("a shared package resolved to another version is refused and nothing is written", func(t *testing.T) {
		win := filepath.Join(t.TempDir(), "win.txt")
		out, err := runWindowsLock(t, strings.Replace(winBody, "onnxruntime==1.31.0", "onnxruntime==1.31.1", 1), linux, win)
		if err == nil || !strings.Contains(out, "onnxruntime: Linux 1.31.0, Windows 1.31.1") {
			t.Errorf("= %v:\n%s", err, out)
		}
		if _, serr := os.Stat(win); serr == nil {
			t.Error("a lock was written")
		}
	})

	t.Run("--check-shared passes on the committed pair and fails on a stray", func(t *testing.T) {
		win := filepath.Join(t.TempDir(), "win.txt")
		if err := os.WriteFile(win, []byte(wantHeader+winBody), 0o644); err != nil {
			t.Fatal(err)
		}
		if out, err := runWindowsLock(t, "", linux, win, "--check-shared"); err != nil {
			t.Fatalf("%v:\n%s", err, out)
		}
		for name, bad := range map[string]string{
			"onnxruntime: Linux 1.31.0, Windows 1.31.1": strings.Replace(winBody, "onnxruntime==1.31.0", "onnxruntime==1.31.1", 1),
			"newpkg==1.0: only in the Windows lock":     winBody + "newpkg==1.0" + hash("b"),
		} {
			_ = os.WriteFile(win, []byte(wantHeader+bad), 0o644)
			out, err := runWindowsLock(t, "", linux, win, "--check-shared")
			if err == nil || !strings.Contains(out, name) {
				t.Errorf("--check-shared on %q = %v:\n%s", name, err, out)
			}
		}
		if lastFake == "" || func() bool { c, _ := os.ReadFile(filepath.Join(lastFake, "calls")); return len(c) != 0 }() {
			t.Error("--check-shared ran uv or docker: it compares the committed locks offline")
		}
	})

	t.Run("--check passes on other hashes and fails on another version", func(t *testing.T) {
		win := filepath.Join(t.TempDir(), "win.txt")
		_ = os.WriteFile(win, []byte(wantHeader+strings.ReplaceAll(winBody, "5555", "9999")), 0o644)
		if out, err := runWindowsLock(t, winBody, linux, win, "--check"); err != nil {
			t.Fatalf("%v:\n%s", err, out)
		}
		_ = os.WriteFile(win, []byte(wantHeader+strings.Replace(winBody, "winloop==0.8.1", "winloop==0.8.0", 1)), 0o644)
		out, err := runWindowsLock(t, winBody, linux, win, "--check")
		if err == nil || !strings.Contains(out, "winloop==0.8.0") {
			t.Errorf("= %v:\n%s", err, out)
		}
	})
}

// requireCollatingLocale skips (fails on CI) when locale does not order
// "a-b==1" before "a==1" the way en_US does: glibc falls back to C for a
// missing locale, and a locale test would then pass whatever the script does.
func requireCollatingLocale(t *testing.T, locale string) {
	t.Helper()
	cmd := exec.Command("sort")
	cmd.Env = append(os.Environ(), "LC_ALL="+locale)
	cmd.Stdin = strings.NewReader("a-b==1\na==1\n")
	out, err := cmd.Output()
	if err == nil && string(out) == "a==1\na-b==1\n" {
		return
	}
	msg := "locale " + locale + " is not installed (sort under it orders " + strings.ReplaceAll(strings.TrimSpace(string(out)), "\n", ", ") + "): the test would not bite"
	if os.Getenv("CI") != "" {
		t.Fatal(msg)
	}
	t.Skip(msg)
}

// pep440_cmp (scripts/pep440.sh) orders versions as PEP 440 does, under the
// awk on PATH and, when gawk is there, under gawk --posix (CI's mawk knows
// no gawk extension either).
func TestPEP440Cmp(t *testing.T) {
	testtool.SkipWindows(t, "linux-only: POSIX script")
	root, _ := filepath.Abs("..")
	awks := map[string]string{"awk": ""}
	if g, err := exec.LookPath("gawk"); err == nil {
		dir := t.TempDir()
		if err := os.WriteFile(filepath.Join(dir, "awk"), []byte("#!/bin/sh\nexec "+g+" --posix \"$@\"\n"), 0o755); err != nil {
			t.Fatal(err)
		}
		awks["gawk --posix"] = dir
	}
	cases := []struct{ a, b, want string }{
		{"0.66b1", "0.66", "-1"}, {"0.66", "0.66b1", "1"}, {"1.0rc1", "1.0", "-1"},
		{"1.0a1", "1.0b1", "-1"}, {"1.0b2", "1.0rc1", "-1"}, {"1.0a10", "1.0a2", "1"},
		{"1.0.dev1", "1.0a1", "-1"}, {"1.0a1.dev1", "1.0a1", "-1"}, {"1.0", "1.0.post1", "-1"},
		{"1.0.post1.dev1", "1.0.post1", "-1"}, {"1.0", "1.0.post1.dev1", "-1"},
		{"1.0", "1.0.0", "0"}, {"1.10", "1.9", "1"}, {"3.4.11", "3.2.0", "1"}, {"2.9.0", "2.9.0", "0"},
		{"1.45.1", "1.44.0", "1"}, {"0.6.5", "0.6.4", "1"},
	}
	for label, dir := range awks {
		path := os.Getenv("PATH")
		if dir != "" {
			path = dir + ":" + path
		}
		run := func(a, b string) (string, error) {
			cmd := exec.Command("bash", "-c", `. "$1"; pep440_cmp "$2" "$3"`, "_", filepath.Join(root, "scripts", "pep440.sh"), a, b)
			cmd.Env = append(os.Environ(), "PATH="+path)
			out, err := cmd.Output()
			return strings.TrimSpace(string(out)), err
		}
		for _, c := range cases {
			if got, err := run(c.a, c.b); err != nil || got != c.want {
				t.Errorf("%s: pep440_cmp %s %s = %q, %v; want %s", label, c.a, c.b, got, err, c.want)
			}
		}
		for _, bad := range []string{"1!1.0", "1.0+local", "1.0-1", "v1.0", "1.0alpha1", ""} {
			if got, err := run(bad, "1.0"); err == nil {
				t.Errorf("%s: pep440_cmp %q 1.0 = %q, want a failure", label, bad, got)
			}
		}
	}
}
