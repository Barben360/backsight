// fakeLockDocker prints the image's listing from listing.txt and
// fakeLockUV's pip compile writes body.txt to its -o file and keeps its -c
// file as constraints.txt and its input (the last argument) as in.txt; each logs its argv to calls.
const fakeLockDocker = `#!/bin/sh
d=$(dirname "$0")
printf 'docker %s\n' "$*" >> "$d/calls"
cat "$d/listing.txt"
`

const fakeLockUV = `#!/bin/sh
d=$(dirname "$0")
printf 'uv %s\n' "$*" >> "$d/calls"
o= c=
for a; do in=$a; done
cp "$in" "$d/in.txt"
while [ $# -gt 0 ]; do
  [ "$1" = -o ] && o=$2
  [ "$1" = -c ] && c=$2
  shift
done
cp "$c" "$d/constraints.txt"
cat "$d/body.txt" > "$o"
`

// imageListing is the image's python3 --version and site-packages, with
// hindsight-api-slim at hs.
func imageListing(hs string) string {
	return "Python 3.11.17\n__pycache__\n_editable_impl_hindsight_api_slim.pth\nhindsight_api_slim-" + hs +
		".dist-info\npg0\npg0_embedded-0.15.2.dist-info\ntorch-2.13.0+cpu.dist-info\nZope.Interface-7.0.dist-info\n"
}

const lockBody = `hindsight-api-slim==1.1.0 \
    --hash=sha256:1111111111111111111111111111111111111111111111111111111111111111
pg0-embedded==0.15.2 \
    --hash=sha256:2222222222222222222222222222222222222222222222222222222222222222
zope-interface==7.0 \
    --hash=sha256:3333333333333333333333333333333333333333333333333333333333333333
`

// lastFake is the fakes' directory of the last runNativeLock.
var lastFake string

// runNativeLock runs scripts/native-lock.sh with the fakes first on PATH
// and the lock at lock; it returns the fakes' calls, the output and the
// exit error.
func runNativeLock(t *testing.T, listing, body, lock string, args ...string) (calls, out string, err error) {
	calls, out, _, err = runNativeLockIn(t, listing, body, lock, args...)
	return calls, out, err
}

// runNativeLockIn is runNativeLock that also returns the constraints the
// compile was given.
func runNativeLockIn(t *testing.T, listing, body, lock string, args ...string) (calls, out, constraints string, err error) {
	t.Helper()
	root, _ := filepath.Abs("..")
	fake := t.TempDir()
	lastFake = fake
	for name, content := range map[string]string{"docker": fakeLockDocker, "uv": fakeLockUV, "listing.txt": listing, "body.txt": body} {
		if werr := os.WriteFile(filepath.Join(fake, name), []byte(content), 0o755); werr != nil {
			t.Fatal(werr)
		}
	}
	cmd := exec.Command(filepath.Join(root, "scripts", "native-lock.sh"), args...)
	cmd.Env = append(os.Environ(), "PATH="+fake+":"+os.Getenv("PATH"), "NATIVE_LOCK="+lock)
	var b bytes.Buffer
	cmd.Stdout, cmd.Stderr = &b, &b
	err = cmd.Run()
	c, _ := os.ReadFile(filepath.Join(fake, "calls"))
	cons, _ := os.ReadFile(filepath.Join(fake, "constraints.txt"))
	return string(c), b.String(), string(cons), err
}

func TestNativeLockScriptChecksThePin(t *testing.T) {
	testtool.SkipWindows(t, "POSIX script, Linux only")
	pin := pinnedImage(t) // render.go's
	tag := strings.Split(pin, "@")[0]
	tag = tag[strings.LastIndex(tag, ":")+1:]
	lockBody := strings.ReplaceAll(lockBody, "hindsight-api-slim==1.1.0", "hindsight-api-slim=="+tag)
	lockHeader := "# Generated by scripts/native-lock.sh: do not edit.\n# image: " + pin +
		"\n# python: 3.11.17 (image: 3.11.17)\n# platform: x86_64-manylinux_2_28\n"
	t.Run("an image shipping another hindsight than its tag", func(t *testing.T) {
		lock := filepath.Join(t.TempDir(), "lock.txt")
		_ = os.WriteFile(lock, []byte(lockHeader+lockBody), 0o644)
		calls, out, err := runNativeLock(t, imageListing("9.9.9"), lockBody, lock, "--check")
		if err == nil {
			t.Fatalf("--check passed:\n%s", out)
		}
		if !strings.Contains(out, tag) || !strings.Contains(out, "9.9.9") {
			t.Errorf("the refusal names not both versions:\n%s", out)
		}
		if !strings.Contains(calls, "docker run --rm --entrypoint sh "+pin+" -c ") {
			t.Errorf("the image read is not render.go's pin:\n%s", calls)
		}
	})

	t.Run("writes the lock with its header", func(t *testing.T) {
		lock := filepath.Join(t.TempDir(), "lock.txt")
		calls, out, err := runNativeLock(t, imageListing(tag), lockBody, lock)
		if err != nil {
			t.Fatalf("%v:\n%s", err, out)
		}
		in, _ := os.ReadFile(filepath.Join(lastFake, "in.txt"))
		if want := "hindsight-api-slim[local-onnx,embedded-db]==" + tag + "\npg0-embedded==0.15.2\n"; string(in) != want {
			t.Errorf("compiled %q, want %q", in, want)
		}
		got, _ := os.ReadFile(lock)
		if string(got) != lockHeader+lockBody {
			t.Errorf("lock:\n%s\nwant:\n%s", got, lockHeader+lockBody)
		}
		for _, want := range []string{"uv pip compile ", "--generate-hashes", "--python-version 3.11 ", "--python-platform x86_64-manylinux_2_28"} {
			if !strings.Contains(calls, want) {
				t.Errorf("uv pip compile lacks %q:\n%s", want, calls)
			}
		}
	})

	t.Run("--check passes on the same versions, other hashes", func(t *testing.T) {
		lock := filepath.Join(t.TempDir(), "lock.txt")
		committed := lockHeader + strings.ReplaceAll(lockBody, "1111", "9999")
		_ = os.WriteFile(lock, []byte(committed), 0o644)
		if _, out, err := runNativeLock(t, imageListing(tag), lockBody, lock, "--check"); err != nil {
			t.Fatalf("%v:\n%s", err, out)
		}
		if got, _ := os.ReadFile(lock); string(got) != committed {
			t.Error("--check rewrote the lock")
		}
	})

	t.Run("--check fails on another version", func(t *testing.T) {
		lock := filepath.Join(t.TempDir(), "lock.txt")
		_ = os.WriteFile(lock, []byte(lockHeader+strings.Replace(lockBody, "zope-interface==7.0", "zope-interface==6.4", 1)), 0o644)
		_, out, err := runNativeLock(t, imageListing(tag), lockBody, lock, "--check")
		if err == nil || !strings.Contains(out, "zope-interface==6.4") || !strings.Contains(out, "zope-interface==7.0") {
			t.Errorf("--check = %v:\n%s", err, out)
		}
	})

	t.Run("a resolved package missing from the image", func(t *testing.T) {
		lock := filepath.Join(t.TempDir(), "lock.txt")
		body := lockBody + "extra-pkg==1.0 \\\n    --hash=sha256:4444444444444444444444444444444444444444444444444444444444444444\n"
		_, out, err := runNativeLock(t, imageListing(tag), body, lock)
		if err == nil || !strings.Contains(out, "extra-pkg==1.0") {
			t.Errorf("= %v:\n%s", err, out)
		}
		if _, serr := os.Stat(lock); serr == nil {
			t.Error("a lock was written")
		}
	})

	t.Run("the constraints are the image's set without torch", func(t *testing.T) {
		lock := filepath.Join(t.TempDir(), "lock.txt")
		_, out, cons, err := runNativeLockIn(t, imageListing(tag), lockBody, lock)
		if err != nil {
			t.Fatalf("%v:\n%s", err, out)
		}
		if want := "hindsight-api-slim==" + tag + "\npg0-embedded==0.15.2\nzope-interface==7.0\n"; cons != want {
			t.Errorf("constraints:\n%s\nwant:\n%s", cons, want)
		}
	})
}
