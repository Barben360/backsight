#!/usr/bin/env bash
# The license texts and notices of the code linked into backsight's binary:
# the Go standard library and every module `go list -deps` finds for the
# main package, on each release target (a module one target alone links,
# such as cobra's Windows helper, is included). Every license, notice and
# patent file at a module's root is copied whole, so a dual-licensed
# module keeps both texts. The file is embedded in the binary (`backsight
# version --licenses`) and shipped in every archive.
#
#   scripts/third-party-licenses.sh [--check] [OUT]
#
# OUT defaults to internal/licenses/THIRD_PARTY_LICENSES. --check writes
# nothing and fails when OUT differs from what the current go.mod gives
# (CI and goreleaser's before hook); without it, OUT is rewritten (make
# licenses). A module with no license file at its root is an error: its
# text has to be found before it ships. The toolchain is go.mod's
# toolchain line, so the standard library's text is the release's.
# PKG (default ./cmd/backsight) and TARGETS (os/arch list) are for tests.
set -euo pipefail
check=0
if [ "${1:-}" = --check ]; then check=1; shift; fi
out=${1:-internal/licenses/THIRD_PARTY_LICENSES}
pkg=${PKG:-./cmd/backsight}
targets=${TARGETS:-linux/amd64 linux/arm64 darwin/arm64 windows/amd64}
tc=$(sed -n 's/^toolchain \(go[0-9][0-9.]*\)$/\1/p' go.mod)
if [ -n "$tc" ]; then export GOTOOLCHAIN=$tc; fi
export CGO_ENABLED=0 LC_ALL=C

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

for t in $targets; do
  GOOS=${t%/*} GOARCH=${t#*/} go list -deps \
    -f '{{with .Module}}{{if not .Main}}{{.Path}}{{"\t"}}{{if .Replace}}{{.Replace.Dir}}{{else}}{{.Dir}}{{end}}{{end}}{{end}}' \
    "$pkg" >>"$tmp/mods"
done
sort -u "$tmp/mods" | sed '/^$/d' >"$tmp/sorted"
goroot=$(go env GOROOT)

# texts <dir>: the license, notice and patent files at the root of dir.
texts() {
  local f u
  for f in "$1"/*; do
    [ -f "$f" ] || continue
    f=${f##*/}
    u=$(printf '%s' "$f" | tr '[:lower:]' '[:upper:]')
    case $u in
      *.GO) ;;
      LICENSE* | LICENCE* | COPYING* | NOTICE* | PATENTS*) echo "$f" ;;
    esac
  done
}

# section <title> <dir>: the module's header and every text, whole.
section() {
  local f
  printf '\n%s\n%s\n%s\n' "$rule" "$1" "$rule"
  for f in $(texts "$2"); do
    printf '\n--- %s ---\n\n' "$f"
    cat "$2/$f"
    if [ -n "$(tail -c1 "$2/$f")" ]; then echo; fi
  done
}

rule========================================================================
missing=
[ -f "$goroot/LICENSE" ] || missing="$missing
  the Go standard library ($goroot)"
while IFS=$'\t' read -r path dir; do
  if [ -z "$dir" ] || [ -z "$(texts "$dir")" ]; then
    missing="$missing
  $path (${dir:-not downloaded})"
  fi
done <"$tmp/sorted"
if [ -n "$missing" ]; then
  echo "third-party-licenses: no license file at the root of:$missing" >&2
  echo "Find its license text before shipping it, or drop the dependency." >&2
  exit 1
fi

{
  echo "Third-party software in backsight"
  echo
  echo "backsight is MIT-licensed (see LICENSE). Its binary also contains the"
  echo "Go standard library and the Go modules listed below. Their license"
  echo "texts and notices follow, in full, as their licenses require."
  echo "Generated by scripts/third-party-licenses.sh from go.mod: do not edit."
  echo
  echo "- Go standard library (https://go.dev)"
  cut -f1 "$tmp/sorted" | sed 's/^/- /'
  section "Go standard library" "$goroot"
  while IFS=$'\t' read -r path dir; do section "$path" "$dir"; done <"$tmp/sorted"
} >"$tmp/out"

if [ "$check" = 1 ]; then
  if ! cmp -s "$tmp/out" "$out"; then
    echo "third-party-licenses: $out is not what go.mod gives; run make licenses and commit it." >&2
    diff -u "$out" "$tmp/out" 2>&1 | head -40 >&2 || true
    exit 1
  fi
  exit 0
fi
mkdir -p "$(dirname "$out")"
cp "$tmp/out" "$out"
