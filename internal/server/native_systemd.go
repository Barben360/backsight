// The native runtime's two systemd user units (decision 0078; Task 1's
// verdict, rulings R20-R23): <project>-db.service runs pg0's extracted
// postgres in the foreground, <project>-server.service runs hindsight-api
// on it. Both are written through the config editor, like the job units.

// systemdHost is the Linux host: the user's systemd manager.
type systemdHost struct{ n Native }

var (
	_ nativeHost       = systemdHost{}
	_ dbAloneStarter   = systemdHost{}
	_ transientWatcher = systemdHost{}
)

const unitHeader = "# Generated by backsight: do not edit.\n"

// Dir is the user unit directory the scheduler's rule names
// (jobs_install.go).
func (h systemdHost) Dir() string { return h.n.UnitDir }

// Files are the two units, for the database on port pg and the server on
// venv's version.
func (h systemdHost) Files(pg int, venv string) (map[string][]byte, error) {
	return map[string][]byte{
		h.n.DBUnit():     h.dbUnit(pg),
		h.n.ServerUnit(): h.serverUnit(venv),
	}, nil
}

// execPath is s as the program of an Exec line: systemd's quoting (it
// expands no variable there).
func execPath(s string) string { return scheduler.SystemdQuote(s) }

// execArg is s as an argument of an Exec line: systemd's quoting, and $
// doubled (systemd expands $VAR in arguments).
func execArg(s string) string { return strings.ReplaceAll(scheduler.SystemdQuote(s), "$", "$$") }

// pathSetting is s as the value of a path setting (EnvironmentFile=,
// WorkingDirectory=), which takes the rest of the line as is: only the
// specifiers are escaped.
func pathSetting(s string) string { return strings.ReplaceAll(s, "%", "%%") }

// unsetKeys are what the user manager may have imported (systemctl --user
// import-environment) that would change Python, Hugging Face, uv, pip, a
// Postgres client or the loader (ruling R31): both units unset them, then
// set their own HOME, HF_HOME and LD_LIBRARY_PATH.
const unsetKeys = "PYTHONPATH PYTHONHOME PYTHONSTARTUP PYTHONUSERBASE PYTHONNOUSERSITE VIRTUAL_ENV CONDA_PREFIX " +
	"PIP_INDEX_URL PIP_EXTRA_INDEX_URL PIP_REQUIRE_VIRTUALENV UV_INDEX_URL UV_EXTRA_INDEX_URL HF_HUB_OFFLINE HF_ENDPOINT " +
	"HF_HUB_CACHE TRANSFORMERS_CACHE SENTENCE_TRANSFORMERS_HOME PGHOST PGPORT PGUSER PGDATABASE PGPASSFILE PGSERVICEFILE LD_PRELOAD"

// dbUnit runs pg0's postgres in the foreground with fsync on, on loopback
// TCP only (requirement 1; Task 1's C2; ruling R44: no Unix socket, whose
// path a long data directory would push past 107 bytes). It is ready once pg_isready answers, gives
// up as soon as the postmaster is gone, and stops with SIGINT (a fast
// shutdown) then whatever is left in its cgroup (ruling R20). native-check
// refuses a start on a missing, empty or foreign instance (requirement 2).
func (h systemdHost) dbUnit(pg int) []byte {
	n := h.n
	inst := n.installation()
	port := strconv.Itoa(pg)
	var b strings.Builder
	b.WriteString(unitHeader)
	b.WriteString("[Unit]\nDescription=backsight memory database (pg0 " + nativelock.PG0 + ")\n\n[Service]\nType=simple\n")
	b.WriteString("UnsetEnvironment=" + unsetKeys + "\n")
	env := map[string]string{}
	for k, v := range n.Env {
		env[k] = v
	}
	env["HOME"] = n.Home()
	env["LD_LIBRARY_PATH"] = filepath.Join(inst, "lib")
	for _, k := range slices.Sorted(func(yield func(string) bool) {
		for k := range env {
			if !yield(k) {
				return
			}
		}
	}) {
		b.WriteString("Environment=" + scheduler.SystemdQuote(k+"="+env[k]) + "\n")
	}
	pre := execPath(n.shim())
	if n.UserHome != "" {
		pre = "/usr/bin/env " + execArg("HOME="+n.UserHome) + " " + execArg(n.shim())
	}
	b.WriteString("ExecStartPre=" + pre + " server native-check\n")
	start := []string{execPath(n.pgBin("postgres")), "-D", execArg(n.DataDir()), "-p", port,
		"-c", "fsync=on", "-c", "listen_addresses=127.0.0.1", "-c", "unix_socket_directories="}
	for _, s := range pgSettings {
		start = append(start, "-c", s)
	}
	b.WriteString("ExecStart=" + strings.Join(start, " ") + "\n")
	ready := "while kill -0 $MAINPID 2>/dev/null; do " + shellWord(n.pgBin("pg_isready")) +
		" -q -h 127.0.0.1 -p " + port + " && exit 0; sleep 0.1; done; exit 1"
	b.WriteString("ExecStartPost=/bin/sh -c " + execArg(ready) + "\n")
	// native-check, a crash recovery and readiness, never cut short into a
	// restart loop (Task 1 measured with 120 s).
	b.WriteString("TimeoutStartSec=300\nKillMode=mixed\nKillSignal=SIGINT\nRestart=on-failure\nTimeoutStopSec=60\n\n[Install]\nWantedBy=default.target\n")
	return []byte(b.String())
}

// serverUnit runs version v's hindsight-api on the database unit, its
// whole environment from server.env; everything it starts dies with it
// (requirement 3).
func (h systemdHost) serverUnit(v string) []byte {
	n := h.n
	db := n.DBUnit()
	return []byte(unitHeader + "[Unit]\nDescription=backsight memory server (Hindsight " + HindsightVersionOf(v) + ")\n" +
		"Requires=" + db + "\nAfter=" + db + "\n\n[Service]\nType=simple\n" +
		"UnsetEnvironment=" + unsetKeys + " LD_LIBRARY_PATH\n" +
		"EnvironmentFile=" + pathSetting(n.EnvFile()) + "\nWorkingDirectory=" + pathSetting(n.Root()) + "\n" +
		"ExecStart=" + execPath(n.venvBin(v, "hindsight-api")) + "\n" +
		"KillMode=control-group\nRestart=on-failure\nTimeoutStopSec=60\n\n[Install]\nWantedBy=default.target\n")
}

func (h systemdHost) systemctl(ctx context.Context, args ...string) ([]byte, error) {
	return h.n.sys(ctx, "systemctl", append([]string{"--user"}, args...)...)
}

// StartDB reloads the units, then enables the database unit and starts
// it (with linger it starts at boot), or restarts it.
func (h systemdHost) StartDB(ctx context.Context, restart bool) error {
	if _, err := h.systemctl(ctx, "daemon-reload"); err != nil {
		return err
	}
	return h.enableAndStart(ctx, h.n.DBUnit(), restart)
}

// startDBAlone reloads the units and starts the database unit, enabling
// nothing.
func (h systemdHost) startDBAlone(ctx context.Context) error {
	if _, err := h.systemctl(ctx, "daemon-reload"); err != nil {
		return err
	}
	_, err := h.systemctl(ctx, "start", h.n.DBUnit())
	return err
}

func (h systemdHost) StartAPI(ctx context.Context, restart bool) error {
	return h.enableAndStart(ctx, h.n.ServerUnit(), restart)
}

// enableAndStart enables unit and starts it, or restarts it when it may
// run with an old file or environment.
func (h systemdHost) enableAndStart(ctx context.Context, unit string, restart bool) error {
	if !restart {
		_, err := h.systemctl(ctx, "enable", "--now", unit)
		return err
	}
	if _, err := h.systemctl(ctx, "enable", unit); err != nil {
		return err
	}
	_, err := h.systemctl(ctx, "restart", unit)
	return err
}

// StopAPI stops the server unit; the database keeps running.
func (h systemdHost) StopAPI(ctx context.Context) error {
	if !pathExists(filepath.Join(h.n.UnitDir, h.n.ServerUnit())) {
		return nil
	}
	_, err := h.systemctl(ctx, "stop", h.n.ServerUnit())
	return err
}

// Stop stops and disables both units: nothing starts at boot (RF 2).
func (h systemdHost) Stop(ctx context.Context) error {
	units := h.n.installedUnits()
	if len(units) == 0 {
		return nil
	}
	_, err := h.systemctl(ctx, append([]string{"disable", "--now"}, units...)...)
	return err
}

// Remove stops and disables what is still installed, then reloads the
// units: the manager forgets those whose files the caller removed.
func (h systemdHost) Remove(ctx context.Context) error {
	if err := h.Stop(ctx); err != nil {
		return err
	}
	_, err := h.systemctl(ctx, "daemon-reload")
	return err
}

func (h systemdHost) StopCmd() string {
	return "systemctl --user disable --now " + h.n.ServerUnit() + " " + h.n.DBUnit()
}

// States are the installed units' ActiveState, each with its SubState
// after a slash.
func (h systemdHost) States(ctx context.Context) (map[string]string, error) {
	installed, states, err := h.showStates(ctx)
	if err != nil {
		return nil, err
	}
	out := map[string]string{}
	for i, u := range installed {
		out[u[1]] = states[i][0]
		if states[i][1] != "" {
			out[u[1]] += "/" + states[i][1]
		}
	}
	return out, nil
}

// showStates asks systemd for the installed units' ActiveState and
// SubState, in units() order.
func (h systemdHost) showStates(ctx context.Context) (installed [][2]string, states [][2]string, err error) {
	var names []string
	for _, u := range h.n.units() {
		if pathExists(filepath.Join(h.n.UnitDir, u[0])) {
			installed, names = append(installed, u), append(names, u[0])
		}
	}
	if len(names) == 0 {
		return nil, nil, nil
	}
	out, err := h.systemctl(ctx, append([]string{"show", "-p", "ActiveState,SubState"}, names...)...)
	if err != nil {
		return nil, nil, err
	}
	var active, sub string
	flush := func() {
		if active != "" && len(states) < len(names) {
			states = append(states, [2]string{active, sub})
		}
		active, sub = "", ""
	}
	for _, l := range strings.Split(string(out), "\n") {
		l = strings.TrimSpace(l)
		switch {
		case l == "":
			flush()
		case strings.HasPrefix(l, "ActiveState="):
			active = strings.TrimPrefix(l, "ActiveState=")
		case strings.HasPrefix(l, "SubState="):
			sub = strings.TrimPrefix(l, "SubState=")
		}
	}
	flush()
	if len(states) != len(names) {
		return nil, nil, fmt.Errorf("systemctl --user show: %d states for %d units: %q", len(states), len(names), out)
	}
	return installed, states, nil
}

// Logs is the journal of service's unit (db or hindsight).
func (h systemdHost) Logs(ctx context.Context, service string, lines int) (string, error) {
	for _, u := range h.n.units() {
		if u[1] == service {
			out, err := h.n.sys(ctx, "journalctl", "--user", "-u", u[0], "-n", strconv.Itoa(lines), "--no-pager", "-o", "cat")
			return string(out), err
		}
	}
	return "", fmt.Errorf("no service %q on the native server: db or hindsight", service)
}

// DeployedVenv reads the version off the server unit's ExecStart.
func (h systemdHost) DeployedVenv(files map[string][]byte) (string, error) {
	return h.deployedFrom(files[h.n.ServerUnit()])
}

// deployedFrom reads the version off a server unit's ExecStart.
func (h systemdHost) deployedFrom(unit []byte) (string, error) {
	start := ""
	for _, l := range strings.Split(string(unit), "\n") {
		if v, ok := strings.CutPrefix(l, "ExecStart="); ok {
			start = systemdUnquote(strings.TrimSpace(v))
		}
	}
	venvs := filepath.Join(h.n.Root(), "venv")
	sep := string(filepath.Separator)
	rest, ok := strings.CutPrefix(start, venvs+sep)
	v, ok2 := strings.CutSuffix(rest, filepath.Join(sep, "bin", "hindsight-api"))
	if !ok || !ok2 || v == "" || strings.Contains(v, sep) {
		return "", fmt.Errorf("ExecStart=%s is not one of %s's venvs", start, venvs)
	}
	return v, nil
}

// systemdUnquote reads back the program execPath wrote.
func systemdUnquote(s string) string {
	if len(s) >= 2 && s[0] == '"' && s[len(s)-1] == '"' {
		s = strings.NewReplacer(`\\`, `\`, `\"`, `"`).Replace(s[1 : len(s)-1])
	}
	return strings.ReplaceAll(s, "%%", "%")
}

// Owns: pid's cgroup is the database unit's.
func (h systemdHost) Owns(pid int) bool {
	cg, ok := h.n.cgroupOf(pid)
	return ok && strings.HasSuffix(cg, "/"+h.n.DBUnit())
}

// Engine is the user's systemd manager: it must answer; its version is
// systemctl's.
func (h systemdHost) Engine(ctx context.Context) (Engine, error) {
	if _, err := h.systemctl(ctx, "show-environment"); err != nil {
		return Engine{}, err
	}
	out, err := h.n.sys(ctx, "systemctl", "--version")
	if err != nil {
		return Engine{}, err
	}
	first, _, _ := strings.Cut(strings.TrimSpace(string(out)), "\n")
	return Engine{Version: strings.TrimSpace(first)}, nil
}

// unpackMaxSec bounds the unpack unit: a killed backsight leaves nothing
// running beyond it.
const unpackMaxSec = 600

// verifyMaxSec is VerifyDump's throwaway unit's lifetime, so that a
// killed backsight leaves nothing running beyond it.
const verifyMaxSec = 3600

// systemdTransient is how a transient job runs under systemd-run.
type systemdTransient struct {
	// wait: --wait --pipe, the call returns once the steps ended; else it
	// returns once the unit started, its last step exec'd (a server the
	// caller then uses), and the unit runs until stopTransient or maxSec.
	wait   bool
	maxSec int  // RuntimeMaxSec=, 0: none
	unset  bool // UnsetEnvironment=unsetKeys
	reset  bool // stopTransient also clears its failed state
}

// transient is the settings of the transient unit name: createInstance's
// db-init, unpackPostgres' unpack, VerifyDump's throwaway database.
func (h systemdHost) transient(name string) (systemdTransient, error) {
	p := h.n.project()
	switch {
	case name == p+"-db-init":
		return systemdTransient{wait: true}, nil
	case name == h.n.unpackUnit():
		return systemdTransient{wait: true, maxSec: unpackMaxSec, unset: true, reset: true}, nil
	case strings.HasPrefix(name, p+"-verify-") && strings.HasSuffix(name, ".service"):
		return systemdTransient{maxSec: verifyMaxSec, unset: true}, nil
	}
	return systemdTransient{}, fmt.Errorf("no transient unit %q on the native server", name)
}

// Transient runs the steps as one /bin/sh script in the transient unit
// name, with KillMode=control-group: everything it starts dies with the
// unit.
func (h systemdHost) Transient(ctx context.Context, name string, env []string, stdin io.Reader, argv [][]string) error {
	t, err := h.transient(name)
	if err != nil {
		return err
	}
	args := []string{"--user"}
	if t.wait {
		args = append(args, "--wait")
	}
	args = append(args, "--collect")
	if t.wait {
		args = append(args, "--pipe")
	}
	args = append(args, "--quiet", "--unit", name, "-p", "KillMode=control-group")
	if t.maxSec > 0 {
		args = append(args, "-p", "RuntimeMaxSec="+strconv.Itoa(t.maxSec))
	}
	if t.unset {
		args = append(args, "-p", "UnsetEnvironment="+unsetKeys)
	}
	for _, e := range env {
		args = append(args, "-E", e)
	}
	// The service manager expands ${VAR} and $VAR in a transient unit's
	// command line, as in ExecStart=, and turns $$ into $ (systemd-run(1),
	// --expand-environment, on by default): every $ is doubled so the
	// script reaches sh as written. It uses no variable today; a $ in a
	// path would otherwise be expanded away.
	args = append(args, "/bin/sh", "-c", strings.ReplaceAll(stepScript(argv, !t.wait), "$", "$$"))
	_, err = h.n.Tools.Run(ctx, systemdRunEnv(), stdin, "systemd-run", args...)
	return err
}

// transientRunning: the unit is neither failed nor inactive (gone).
func (h systemdHost) transientRunning(ctx context.Context, name string) bool {
	out, _ := h.systemctl(ctx, "is-active", name)
	s := strings.TrimSpace(string(out))
	return s != "failed" && s != "inactive"
}

// stopTransient stops the unit and, for the unpack unit, clears its
// failed state. A unit that is not there is no error worth reporting.
func (h systemdHost) stopTransient(ctx context.Context, name string) {
	_, _ = h.systemctl(ctx, "stop", name)
	if t, err := h.transient(name); err == nil && t.reset {
		_, _ = h.systemctl(ctx, "reset-failed", name)
	}
}

// stepScript is steps as one sh script: each word quoted for sh (a
// KEY=value word's value only), the redirections as they are, the steps
// joined by &&; when execLast, exec runs the last one, after its own
// environment, in the shell's place (the unit's main process).
func stepScript(steps [][]string, execLast bool) string {
	parts := make([]string, 0, len(steps))
	for i, st := range steps {
		env := 0
		for env < len(st) && envWord.MatchString(st[env]) {
			env++
		}
		words := make([]string, 0, len(st)+1)
		for j, w := range st {
			if execLast && i == len(steps)-1 && j == env {
				words = append(words, "exec")
			}
			words = append(words, stepWord(w))
		}
		parts = append(parts, strings.Join(words, " "))
	}
	return strings.Join(parts, " && ")
}

// envWord is a step's leading KEY=value: its own environment.
var envWord = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*=`)

// assignWord is a KEY=value or --option=value word.
var assignWord = regexp.MustCompile(`^(-{0,2}[A-Za-z_][A-Za-z0-9_-]*=)(.*)$`)

// stepWord is one word of a step for sh.
func stepWord(w string) string {
	if w == stepNoStdin || w == stepNoStdout {
		return w
	}
	if m := assignWord.FindStringSubmatch(w); m != nil {
		if m[2] == "" {
			return m[1]
		}
		return m[1] + shellWord(m[2])
	}
	return shellWord(w)
}

// systemdRunEnv is systemd-run's own environment: it reaches the user
// manager through the session's bus.
func systemdRunEnv() []string {
	env := []string{"PATH=/usr/bin:/bin", "LANG=C.UTF-8"}
	for _, k := range []string{"XDG_RUNTIME_DIR", "DBUS_SESSION_BUS_ADDRESS"} {
		if v := os.Getenv(k); v != "" {
			env = append(env, k+"="+v)
		}
	}
	return env
}
