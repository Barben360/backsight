// Render builds server.env and the two units for Version. The database's
// port is the one server.env already names, else the first free one after
// the API's.
func (n Native) Render(sec config.Secrets, host string) (Files, error) {
	if n.Err != nil {
		return Files{}, n.Err
	}
	cfg := n.Cfg
	if err := checkRenderable(cfg, sec); err != nil {
		return Files{}, err
	}
	for _, p := range []string{n.Root(), n.shim()} {
		if strings.ContainsAny(p, "\n\r") {
			return Files{}, fmt.Errorf("%q: a unit file cannot carry a path with a line break", p)
		}
	}
	api, err := cfg.APIPort()
	if err != nil {
		return Files{}, err
	}
	pg, err := n.pgPort(api)
	if err != nil {
		return Files{}, err
	}
	env := &envFile{}
	env.comment(envHeader)
	dsn := url.URL{Scheme: "postgresql", User: url.UserPassword("hindsight", sec.DBPassword),
		Host: net.JoinHostPort("127.0.0.1", strconv.Itoa(pg)), Path: "/hindsight"}
	cfg.LLM.BaseURL = onThisHost(cfg.LLM.BaseURL)
	hindsightEnv(env, cfg, sec, host, dsn.String(), false)
	env.comment("Native runtime: the API on this PC only, the models in HF_HOME, the database's port kept across renders.")
	env.plain("HINDSIGHT_API_HOST", "127.0.0.1")
	env.plain("HINDSIGHT_API_PORT", strconv.Itoa(api))
	env.quoted("HOME", n.Home())
	env.quoted("HF_HOME", n.HF())
	env.plain(pgPortKey, strconv.Itoa(pg))
	if env.err != nil {
		return Files{}, env.err
	}
	return Files{Env: env.buf.Bytes(), Units: map[string][]byte{
		n.DBUnit():     n.dbUnit(pg),
		n.ServerUnit(): n.serverUnit(n.VenvDir(n.Version())),
	}}, nil
}

// onThisHost is an LLM base URL as the native server reaches it:
// Docker's name for the host, host.docker.internal, is 127.0.0.1 there
// (ruling R32).
func onThisHost(base string) string {
	u, err := url.Parse(base)
	if err != nil || u.Hostname() != "host.docker.internal" {
		return base
	}
	port := u.Port()
	u.Host = "127.0.0.1"
	if port != "" {
		u.Host = net.JoinHostPort("127.0.0.1", port)
	}
	return u.String()
}

// checkRenderable refuses what neither runtime can render: another
// embeddings preset, a missing secret.
func checkRenderable(cfg config.Config, sec config.Secrets) error {
	if cfg.Embeddings.Preset != "multilingual" {
		return fmt.Errorf("embeddings preset %q is not available yet: use multilingual", cfg.Embeddings.Preset)
	}
	var missing []string
	have := sec.Names()
	for name, needed := range config.RequiredSecrets(cfg) {
		if needed && !have[name] {
			missing = append(missing, name)
		}
	}
	if len(missing) > 0 {
		slices.Sort(missing)
		return &MissingSecretsError{Names: missing}
	}
	return nil
}

// pgPort is server.env's database port, else a free one after the API's,
// never the API's or the UI's.
func (n Native) pgPort(api int) (int, error) {
	if p, err := n.envPort(); err == nil {
		return p, nil
	}
	return freePort(api+1, api, n.Cfg.Server.UIPort)
}

// envPort reads the database's port from server.env.
func (n Native) envPort() (int, error) {
	raw, err := os.ReadFile(n.EnvFile())
	if err != nil {
		return 0, fmt.Errorf("the native server's environment: %w (run backsight server render)", err)
	}
	for _, kv := range parseEnvFile(raw) {
		if v, ok := strings.CutPrefix(kv, pgPortKey+"="); ok {
			if p, err := strconv.Atoi(v); err == nil && p > 0 && p <= 65535 {
				return p, nil
			}
		}
	}
	return 0, fmt.Errorf("%s names no database port (%s): run backsight server render", n.EnvFile(), pgPortKey)
}

// parseEnvFile reads the KEY=value lines of an environment file Render
// wrote, without the quotes quoted() adds.
func parseEnvFile(raw []byte) []string {
	var out []string
	sc := bufio.NewScanner(bytes.NewReader(raw))
	for sc.Scan() {
		l := strings.TrimSpace(sc.Text())
		k, v, ok := strings.Cut(l, "=")
		if !ok || l == "" || strings.HasPrefix(l, "#") {
			continue
		}
		if len(v) >= 2 && v[0] == '\'' && v[len(v)-1] == '\'' {
			v = v[1 : len(v)-1]
		}
		out = append(out, k+"="+v)
	}
	return out
}

// execPath is s as the program of an Exec line: systemd's quoting (it
// expands no variable there).
func execPath(s string) string { return scheduler.SystemdQuote(s) }

// execArg is s as an argument of an Exec line: systemd's quoting, and $
// doubled (systemd expands $VAR in arguments).
func execArg(s string) string { return strings.ReplaceAll(scheduler.SystemdQuote(s), "$", "$$") }

// pathSetting is s as the value of a path setting (EnvironmentFile=,
// WorkingDirectory=), which takes the rest of the line as is: only the
// specifiers are escaped.
func pathSetting(s string) string { return strings.ReplaceAll(s, "%", "%%") }

// shellWord is s as one word for /bin/sh.
func shellWord(s string) string {
	if s != "" && safeShellWord.MatchString(s) {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

var safeShellWord = regexp.MustCompile(`^[A-Za-z0-9_./:=@+-]+$`)

// unsetKeys are what the user manager may have imported (systemctl --user
// import-environment) that would change Python, Hugging Face, uv, pip, a
// Postgres client or the loader (ruling R31): both units unset them, then
// set their own HOME, HF_HOME and LD_LIBRARY_PATH.
const unsetKeys = "PYTHONPATH PYTHONHOME PYTHONSTARTUP PYTHONUSERBASE PYTHONNOUSERSITE VIRTUAL_ENV CONDA_PREFIX " +
	"PIP_INDEX_URL PIP_EXTRA_INDEX_URL PIP_REQUIRE_VIRTUALENV UV_INDEX_URL UV_EXTRA_INDEX_URL HF_HUB_OFFLINE HF_ENDPOINT " +
	"HF_HUB_CACHE TRANSFORMERS_CACHE SENTENCE_TRANSFORMERS_HOME PGHOST PGPORT PGUSER PGDATABASE PGPASSFILE PGSERVICEFILE LD_PRELOAD"

// pgSettings are pg0's own settings, which a postgres started directly
// would otherwise not get (ruling R23).
var pgSettings = []string{"shared_buffers=256MB", "work_mem=64MB", "maintenance_work_mem=512MB", "effective_cache_size=1GB",
	"max_parallel_maintenance_workers=4", "timezone=UTC", "log_timezone=UTC"}

// dbUnit runs pg0's postgres in the foreground with fsync on, on loopback
// (requirement 1; Task 1's C2). It is ready once pg_isready answers, gives
// up as soon as the postmaster is gone, and stops with SIGINT (a fast
// shutdown) then whatever is left in its cgroup (ruling R20). native-check
// refuses a start on a missing, empty or foreign instance (requirement 2).
func (n Native) dbUnit(pg int) []byte {
	inst := n.installation()
	port := strconv.Itoa(pg)
	var b strings.Builder
	b.WriteString(unitHeader)
	b.WriteString("[Unit]\nDescription=backsight memory database (pg0 " + nativelock.PG0 + ")\n\n[Service]\nType=simple\n")
	b.WriteString("UnsetEnvironment=" + unsetKeys + "\n")
	env := map[string]string{}
	for k, v := range n.Env {
		env[k] = v
	}
	env["HOME"] = n.Home()
	env["LD_LIBRARY_PATH"] = filepath.Join(inst, "lib")
	for _, k := range slices.Sorted(func(yield func(string) bool) {
		for k := range env {
			if !yield(k) {
				return
			}
		}
	}) {
		b.WriteString("Environment=" + scheduler.SystemdQuote(k+"="+env[k]) + "\n")
	}
	b.WriteString("ExecStartPre=" + execPath(n.shim()) + " server native-check\n")
	start := []string{execPath(filepath.Join(inst, "bin", "postgres")), "-D", execArg(n.DataDir()), "-p", port,
		"-c", "fsync=on", "-c", "listen_addresses=127.0.0.1", "-k", execArg(n.socketDir())}
	for _, s := range pgSettings {
		start = append(start, "-c", s)
	}
	b.WriteString("ExecStart=" + strings.Join(start, " ") + "\n")
	ready := "while kill -0 $MAINPID 2>/dev/null; do " + shellWord(filepath.Join(inst, "bin", "pg_isready")) +
		" -q -h " + shellWord(n.socketDir()) + " -p " + port + " && exit 0; sleep 0.1; done; exit 1"
	b.WriteString("ExecStartPost=/bin/sh -c " + execArg(ready) + "\n")
	// native-check, a crash recovery and readiness, never cut short into a
	// restart loop (Task 1 measured with 120 s).
	b.WriteString("TimeoutStartSec=300\nKillMode=mixed\nKillSignal=SIGINT\nRestart=on-failure\nTimeoutStopSec=60\n\n[Install]\nWantedBy=default.target\n")
	return []byte(b.String())
}

// serverUnit runs venv's hindsight-api on the database unit, its whole
// environment from server.env; everything it starts dies with it
// (requirement 3).
func (n Native) serverUnit(venv string) []byte {
	db := n.DBUnit()
	return []byte(unitHeader + "[Unit]\nDescription=backsight memory server (Hindsight " + HindsightVersionOf(filepath.Base(venv)) + ")\n" +
		"Requires=" + db + "\nAfter=" + db + "\n\n[Service]\nType=simple\n" +
		"UnsetEnvironment=" + unsetKeys + " LD_LIBRARY_PATH\n" +
		"EnvironmentFile=" + pathSetting(n.EnvFile()) + "\nWorkingDirectory=" + pathSetting(n.Root()) + "\n" +
		"ExecStart=" + execPath(filepath.Join(venv, "bin", "hindsight-api")) + "\n" +
		"KillMode=control-group\nRestart=on-failure\nTimeoutStopSec=60\n\n[Install]\nWantedBy=default.target\n")
}

// Write installs f: server.env (0600) and home/ (0700) directly, the units
// through the config editor, each only when it changed. A change under a
// unit that already existed is recorded in restart-pending first (ruling
// R1): the next Start restarts what runs.
func (n Native) Write(f Files) (Changes, error) { return n.write(f, true) }

// Diff is what Write would change, writing nothing.
func (n Native) Diff(f Files) (Changes, error) { return n.write(f, false) }

func (n Native) write(f Files, apply bool) (Changes, error) {
	var c Changes
	if n.Err != nil {
		return c, n.Err
	}
	if n.UnitDir == "" {
		return c, errors.New("no systemd user unit directory for the native server")
	}
	var err error
	if c.Env, err = differs(n.EnvFile(), f.Env); err != nil {
		return c, err
	}
	var restart []string
	if c.Env && pathExists(n.EnvFile()) {
		restart = append(restart, n.ServerUnit())
	}
	var edits []claudecfg.Edit
	for _, name := range slices.Sorted(func(yield func(string) bool) {
		for k := range f.Units {
			if !yield(k) {
				return
			}
		}
	}) {
		path, content := filepath.Join(n.UnitDir, name), string(f.Units[name])
		d, err := differs(path, f.Units[name])
		if err != nil {
			return c, err
		}
		if !d {
			continue
		}
		c.Units = true
		if pathExists(path) {
			restart = append(restart, n.ServerUnit())
			if name == n.DBUnit() {
				restart = append(restart, n.DBUnit())
			}
		}
		edits = append(edits, claudecfg.Edit{Target: path, Apply: func(doc []byte) ([]byte, []claudecfg.Change, error) {
			var before *string
			if doc != nil {
				old := string(doc)
				before = &old
			}
			return []byte(content), []claudecfg.Change{{Path: "(whole file)", Old: before, New: &content}}, nil
		}})
	}
	if !apply {
		return c, nil
	}
	if err := os.MkdirAll(n.Root(), 0o755); err != nil {
		return c, err
	}
	if err := n.ensureHome(); err != nil {
		return c, err
	}
	if err := os.MkdirAll(n.socketDir(), 0o700); err != nil {
		return c, err
	}
	if err := os.Chmod(n.socketDir(), 0o700); err != nil {
		return c, err
	}
	if len(restart) > 0 {
		if err := n.markRestart(restart); err != nil {
			return c, err
		}
	}
	if c.Env {
		if err := fsutil.WriteAtomic(n.EnvFile(), f.Env, 0o600); err != nil {
			return c, err
		}
	} else if fi, err := os.Stat(n.EnvFile()); err == nil && fi.Mode().Perm() != 0o600 {
		if err := os.Chmod(n.EnvFile(), 0o600); err != nil { // loosened by hand: it holds secrets
			return c, err
		}
	}
	if len(edits) > 0 {
		if _, _, err := n.editor("server render").Apply(edits); err != nil {
			return c, err
		}
	}
	return c, nil
}

func (n Native) editor(command string) claudecfg.Runner {
	return claudecfg.Runner{PreImages: n.Dirs.PreImagesDir(), Journal: n.Dirs.JournalFile(), Command: command}
}

func pathExists(p string) bool { _, err := os.Lstat(p); return err == nil }

// markRestart adds units to restart-pending.
func (n Native) markRestart(units []string) error {
	have := n.pending()
	for _, u := range units {
		have[u] = true
	}
	var lines []string
	for _, u := range []string{n.DBUnit(), n.ServerUnit()} {
		if have[u] {
			lines = append(lines, u)
		}
	}
	return fsutil.WriteAtomic(n.pendingFile(), []byte(strings.Join(lines, "\n")+"\n"), 0o644)
}

// pending reads restart-pending: a marker naming no unit of ours restarts
// the server.
func (n Native) pending() map[string]bool {
	out := map[string]bool{}
	raw, err := os.ReadFile(n.pendingFile())
	if err != nil {
		return out
	}
	for _, l := range strings.Fields(string(raw)) {
		if l == n.DBUnit() || l == n.ServerUnit() {
			out[l] = true
		}
	}
	if len(out) == 0 {
		out[n.ServerUnit()] = true
	}
	return out
}

// redactedError is an error whose text had the secrets taken out; it
// still wraps the original (exec.ErrNotFound stays visible).
type redactedError struct {
	msg string
	err error
}

func (e *redactedError) Error() string { return e.msg }
func (e *redactedError) Unwrap() error { return e.err }

// secrets are secrets.toml's, for redaction; none when it cannot be read.
func (n Native) secrets() config.Secrets {
	if n.Dirs.Config == "" {
		return config.Secrets{}
	}
	sec, _ := config.LoadSecrets(n.Dirs.SecretsFile())
	return sec
}

// redact is err with every secret replaced.
func (n Native) redact(err error) error {
	if err == nil {
		return nil
	}
	return &redactedError{msg: Redact(err.Error(), n.secrets()), err: err}
}

// sys runs a system tool; its error carries the output, redacted.
func (n Native) sys(ctx context.Context, name string, args ...string) ([]byte, error) {
	out, err := n.Sys.Run(ctx, name, args...)
	if err == nil {
		return out, nil
	}
	err = fmt.Errorf("%s %s: %w", name, strings.Join(args, " "), err)
	if t := strings.TrimSpace(string(out)); t != "" {
		err = fmt.Errorf("%w: %s", err, t)
	}
	return out, n.redact(err)
}

func (n Native) systemctl(ctx context.Context, args ...string) ([]byte, error) {
	return n.sys(ctx, "systemctl", append([]string{"--user"}, args...)...)
}

// dbPassword is secrets.toml's db_password, the only source of it (ruling
// R11).
func (n Native) dbPassword() (string, error) {
	sec, err := config.LoadSecrets(n.Dirs.SecretsFile())
	if err != nil {
		return "", err
	}
	if sec.DBPassword == "" {
		return "", errors.New("secrets.toml holds no db_password: run backsight secret set db_password")
	}
	if strings.ContainsAny(sec.DBPassword, "'\\\n\r") {
		return "", errors.New("db_password holds a quote, backslash or line break: set another (backsight secret set db_password)")
	}
	return sec.DBPassword, nil
}

// pgEnv is a bundled Postgres client's whole environment: the password in
// PGPASSWORD, never on its argv.
func (n Native) pgEnv(password string) []string {
	return append(n.toolEnv(), "PGPASSWORD="+password)
}

// waitDB waits until the database answers a query as hindsight, dbWait at
// most.
func (n Native) waitDB(ctx context.Context) error {
	pw, err := n.dbPassword()
	if err != nil {
		return err
	}
	port, err := n.envPort()
	if err != nil {
		return err
	}
	psql := filepath.Join(n.installation(), "bin", "psql")
	deadline := time.Now().Add(dbWait)
	for {
		_, err := n.Tools.Run(ctx, n.pgEnv(pw), nil, psql, "-h", "127.0.0.1", "-p", strconv.Itoa(port),
			"-U", "hindsight", "-d", "hindsight", "-At", "-v", "ON_ERROR_STOP=1", "-c", "select 1")
		if err == nil {
			return nil
		}
		if ctx.Err() != nil || !time.Now().Before(deadline) {
			return n.redact(fmt.Errorf("the database (%s, 127.0.0.1:%d) did not answer within %s: %w", n.DBUnit(), port, dbWait, err))
		}
		select {
		case <-ctx.Done():
		case <-time.After(dbPoll):
		}
	}
}

// Start creates the database on a first install and refuses a missing,
// empty or foreign one (requirement 2), enables both units (with linger
// they start at boot), waits for the database to answer and checks its
// fsync (requirement 1: off stops and disables both), then waits for the
// API to answer with its database connected. What restart-pending lists
// is restarted, and the marker removed only once the API answered
// (rulings R1, R30).
func (n Native) Start(ctx context.Context) error {
	if n.Err != nil {
		return n.Err
	}
	if err := n.checkVenv(); err != nil {
		return err
	}
	if err := n.guardStart(ctx); err != nil {
		return err
	}
	if _, err := n.systemctl(ctx, "daemon-reload"); err != nil {
		return err
	}
	pending := n.pending()
	if !pathExists(n.pendingFile()) {
		pending = map[string]bool{}
	}
	db, srv := n.DBUnit(), n.ServerUnit()
	if err := n.enableAndStart(ctx, db, pending[db]); err != nil {
		return err
	}
	if err := n.waitDB(ctx); err != nil {
		return err
	}
	if err := n.fsyncOrStop(ctx); err != nil {
		return err
	}
	if err := n.enableAndStart(ctx, srv, pending[db] || pending[srv]); err != nil {
		return err
	}
	if err := n.waitAPI(ctx); err != nil {
		return err
	}
	if err := os.Remove(n.pendingFile()); err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	return nil
}

// checkVenv refuses a server unit whose venv is not marked complete
// (rulings R2, R40): an interrupted install, or one removed by hand,
// never runs.
func (n Native) checkVenv() error {
	v, err := n.Deployed()
	if err != nil {
		return err
	}
	if v == "" {
		v = n.Version()
	}
	if !n.venvInstalled(v) {
		return fmt.Errorf("the native server's venv %s is incomplete (no %s): nothing was started; run backsight server install to re-fetch it",
			n.VenvDir(v), venvComplete)
	}
	return nil
}

// waitAPI waits until the API on 127.0.0.1 answers /health with its
// database connected, apiWait at most (ruling R30): Start's callers
// expect a running server, as Docker's compose up --wait gives them.
func (n Native) waitAPI(ctx context.Context) error {
	api, err := n.Cfg.APIPort()
	if err != nil {
		return err
	}
	base := "http://" + net.JoinHostPort("127.0.0.1", strconv.Itoa(api))
	deadline := time.Now().Add(apiWait)
	for {
		db, err := apiHealth(ctx, base)
		if err == nil && db == "connected" {
			return nil
		}
		if err == nil {
			err = fmt.Errorf("its database is %q", db)
		}
		if ctx.Err() != nil || !time.Now().Before(deadline) {
			return n.redact(fmt.Errorf("the server (%s) did not answer %s/health with its database connected within %s (%w): see journalctl --user -u %s",
				n.ServerUnit(), base, apiWait, err, n.ServerUnit()))
		}
		select {
		case <-ctx.Done():
		case <-time.After(apiPoll):
		}
	}
}

// enableAndStart enables unit and starts it, or restarts it when it may
// run with an old file or environment.
func (n Native) enableAndStart(ctx context.Context, unit string, restart bool) error {
	if !restart {
		_, err := n.systemctl(ctx, "enable", "--now", unit)
		return err
	}
	if _, err := n.systemctl(ctx, "enable", unit); err != nil {
		return err
	}
	_, err := n.systemctl(ctx, "restart", unit)
	return err
}

// StartDatabase starts the database unit alone, enabling nothing, behind
// the same guards as Start, and waits until it answers with fsync on.
func (n Native) StartDatabase(ctx context.Context) error {
	if n.Err != nil {
		return n.Err
	}
	if err := n.guardStart(ctx); err != nil {
		return err
	}
	if _, err := n.systemctl(ctx, "daemon-reload"); err != nil {
		return err
	}
	if _, err := n.systemctl(ctx, "start", n.DBUnit()); err != nil {
		return err
	}
	if err := n.waitDB(ctx); err != nil {
		return err
	}
	return n.fsyncOrStop(ctx)
}

// installedUnits are the units whose files exist, the server first.
func (n Native) installedUnits() []string {
	var out []string
	for _, u := range []string{n.ServerUnit(), n.DBUnit()} {
		if pathExists(filepath.Join(n.UnitDir, u)) {
			out = append(out, u)
		}
	}
	return out
}

// StopAPI stops the server unit; the database keeps running.
func (n Native) StopAPI(ctx context.Context) error {
	if n.Err != nil {
		return n.Err
	}
	if !pathExists(filepath.Join(n.UnitDir, n.ServerUnit())) {
		return nil
	}
	_, err := n.systemctl(ctx, "stop", n.ServerUnit())
	return err
}

// Stop stops and disables both units: nothing starts at boot (RF 2).
func (n Native) Stop(ctx context.Context) error {
	if n.Err != nil {
		return n.Err
	}
	units := n.installedUnits()
	if len(units) == 0 {
		return nil
	}
	_, err := n.systemctl(ctx, append([]string{"disable", "--now"}, units...)...)
	return err
}

func (n Native) StopCmd() string {
	return "systemctl --user disable --now " + n.ServerUnit() + " " + n.DBUnit()
}

// Delete stops and disables both units before anything is removed, then
// removes the unit files through the config editor, then Root(): the
// database, the environments and the models.
func (n Native) Delete(ctx context.Context) error {
	if n.Err != nil {
		return n.Err
	}
	units := n.installedUnits()
	if len(units) > 0 {
		if _, err := n.systemctl(ctx, append([]string{"disable", "--now"}, units...)...); err != nil {
			return err
		}
		var edits []claudecfg.Edit
		for _, u := range units {
			edits = append(edits, claudecfg.Edit{Target: filepath.Join(n.UnitDir, u), Apply: func(doc []byte) ([]byte, []claudecfg.Change, error) {
				if doc == nil {
					return nil, nil, nil
				}
				old := string(doc)
				return nil, []claudecfg.Change{{Path: "(whole file)", Old: &old}}, nil
			}})
		}
		if _, _, err := n.editor("server delete").Apply(edits); err != nil {
			return err
		}
		if _, err := n.systemctl(ctx, "daemon-reload"); err != nil {
			return err
		}
	}
	return os.RemoveAll(n.Root())
}

// Status reads each installed unit's state, as Docker's container states:
// none when no unit file exists.
func (n Native) Status(ctx context.Context) ([]Container, error) {
	if n.Err != nil {
		return nil, n.Err
	}
	var names, services []string
	for _, u := range n.units() {
		if pathExists(filepath.Join(n.UnitDir, u[0])) {
			names, services = append(names, u[0]), append(services, u[1])
		}
	}
	if len(names) == 0 {
		return nil, nil
	}
	out, err := n.systemctl(ctx, append([]string{"show", "-p", "ActiveState,SubState"}, names...)...)
	if err != nil {
		return nil, err
	}
	var list []Container
	var active, sub string
	flush := func() {
		if active != "" && len(list) < len(services) {
			list = append(list, Container{Service: services[len(list)], State: unitState(active, sub)})
		}
		active, sub = "", ""
	}
	for _, l := range strings.Split(string(out), "\n") {
		l = strings.TrimSpace(l)
		switch {
		case l == "":
			flush()
		case strings.HasPrefix(l, "ActiveState="):
			active = strings.TrimPrefix(l, "ActiveState=")
		case strings.HasPrefix(l, "SubState="):
			sub = strings.TrimPrefix(l, "SubState=")
		}
	}
	flush()
	if len(list) != len(services) {
		return nil, fmt.Errorf("systemctl --user show: %d states for %d units: %q", len(list), len(services), out)
	}
	return list, nil
}

// unitState names a unit's state as Docker names a container's.
func unitState(active, sub string) string {
	switch active {
	case "active", "reloading":
		return "running"
	case "activating":
		if sub == "auto-restart" {
			return "restarting"
		}
		return "starting"
	case "deactivating":
		return "stopping"
	case "failed":
		return "exited"
	case "inactive":
		return "stopped"
	}
	return active
}

// Logs is the journal of service's unit (db or hindsight).
func (n Native) Logs(ctx context.Context, service string, lines int) (string, error) {
	if n.Err != nil {
		return "", n.Err
	}
	for _, u := range n.units() {
		if u[1] == service {
			out, err := n.sys(ctx, "journalctl", "--user", "-u", u[0], "-n", strconv.Itoa(lines), "--no-pager", "-o", "cat")
			return string(out), err
		}
	}
	return "", fmt.Errorf("no service %q on the native server: db or hindsight", service)
}

// Deployed is the version whose venv the server unit runs, "" without the
// unit.
func (n Native) Deployed() (string, error) {
	if n.Err != nil {
		return "", n.Err
	}
	path := filepath.Join(n.UnitDir, n.ServerUnit())
	raw, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		return "", nil
	}
	if err != nil {
		return "", err
	}
	v, err := n.deployedFrom(raw)
	if err != nil {
		return "", fmt.Errorf("%s: %w", path, err)
	}
	return v, nil
}

// deployedFrom reads the version off a server unit's ExecStart.
func (n Native) deployedFrom(unit []byte) (string, error) {
	start := ""
	for _, l := range strings.Split(string(unit), "\n") {
		if v, ok := strings.CutPrefix(l, "ExecStart="); ok {
			start = systemdUnquote(strings.TrimSpace(v))
		}
	}
	venvs := filepath.Join(n.Root(), "venv")
	rest, ok := strings.CutPrefix(start, venvs+"/")
	v, ok2 := strings.CutSuffix(rest, "/bin/hindsight-api")
	if !ok || !ok2 || v == "" || strings.Contains(v, "/") {
		return "", fmt.Errorf("ExecStart=%s is not one of %s's venvs", start, venvs)
	}
	return v, nil
}

// systemdUnquote reads back the program execPath wrote.
func systemdUnquote(s string) string {
	if len(s) >= 2 && s[0] == '"' && s[len(s)-1] == '"' {
		s = strings.NewReplacer(`\\`, `\`, `\"`, `"`).Replace(s[1 : len(s)-1])
	}
	return strings.ReplaceAll(s, "%%", "%")
}

// runningVenv is the venv the server unit runs, else Version's.
func (n Native) runningVenv() string {
	if v, err := n.Deployed(); err == nil && v != "" {
		return n.VenvDir(v)
	}
	return n.VenvDir(n.Version())
}

