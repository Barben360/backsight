// Render builds compose.yaml and .env for cfg; host names the worker.
func Render(cfg config.Config, sec config.Secrets, host string) (Files, error) {
	if cfg.Embeddings.Preset != "multilingual" {
		return Files{}, fmt.Errorf("embeddings preset %q is not available yet (decision 0049): use multilingual", cfg.Embeddings.Preset)
	}
	var missing []string
	have := sec.Names()
	for name, needed := range config.RequiredSecrets(cfg) {
		if needed && !have[name] {
			missing = append(missing, name)
		}
	}
	if len(missing) > 0 {
		sort.Strings(missing)
		return Files{}, &MissingSecretsError{Names: missing}
	}

	apiPort, err := cfg.APIPort()
	if err != nil {
		return Files{}, err
	}
	bind := "127.0.0.1"
	if cfg.Network.Exposure == "private" {
		bind = cfg.Network.BindIP
	}
	if strings.Contains(bind, ":") { // IPv6: Compose wants [addr]:port
		bind = "[" + bind + "]"
	}
	image := HindsightImage
	if cfg.Server.Digest != "" {
		image = "ghcr.io/vectorize-io/hindsight@" + cfg.Server.Digest
	}
	var compose bytes.Buffer
	if err := composeTmpl.Execute(&compose, map[string]any{"Project": Project, "Postgres": PostgresImage, "Hindsight": image,
		"Bind": bind, "APIPort": apiPort, "UIPort": cfg.Server.UIPort}); err != nil {
		return Files{}, err
	}

	env := &envFile{}
	env.comment("Generated by backsight: holds secrets (mode 0600). Do not edit; run backsight server render.")
	env.quoted("BACKSIGHT_DB_PASSWORD", sec.DBPassword)
	dsn := url.URL{Scheme: "postgresql", User: url.UserPassword("hindsight", sec.DBPassword), Host: "db:5432", Path: "/hindsight"}
	env.quoted("HINDSIGHT_API_DATABASE_URL", dsn.String())
	env.plain("HINDSIGHT_API_TENANT_EXTENSION", "hindsight_api.extensions.builtin.tenant:ApiKeyTenantExtension")
	env.quoted("HINDSIGHT_API_TENANT_API_KEY", sec.APIKey)
	env.quoted("HINDSIGHT_CP_DATAPLANE_API_KEY", sec.APIKey)
	env.quoted("HINDSIGHT_CP_ACCESS_KEY", sec.UIKey)
	env.plain("HINDSIGHT_API_LLM_PROVIDER", cfg.LLM.Provider)
	env.plain("HINDSIGHT_API_LLM_MODEL", cfg.LLM.Model)
	if sec.LLMAPIKey != "" {
		env.quoted("HINDSIGHT_API_LLM_API_KEY", sec.LLMAPIKey)
	}
	if cfg.LLM.BaseURL != "" {
		env.quoted("HINDSIGHT_API_LLM_BASE_URL", cfg.LLM.BaseURL)
	}
	env.plain("HINDSIGHT_API_LLM_TIMEOUT", "300")
	env.comment("Facts, observations and reflect answers always in English (decision 0039).")
	env.plain("HINDSIGHT_API_LLM_OUTPUT_LANGUAGE", "English")
	env.comment("Multilingual preset: multilingual-e5-small (onnx default) + mmarco reranker.")
	env.comment("On CPU reranking is ~98 % of a recall: 30 candidates of at most 128 tokens keep the prompt hook p95 under 2.5 s (E25, decision 0057).")
	env.plain("HINDSIGHT_API_EMBEDDINGS_PROVIDER", "onnx")
	env.plain("HINDSIGHT_API_RERANKER_PROVIDER", "local")
	env.plain("HINDSIGHT_API_RERANKER_LOCAL_MODEL", "cross-encoder/mmarco-mMiniLMv2-L12-H384-v1")
	env.plain("HINDSIGHT_API_RERANKER_LOCAL_BUCKET_BATCHING", "true")
	env.plain("HINDSIGHT_API_RERANKER_MAX_CANDIDATES", "30")
	env.plain("HINDSIGHT_API_RERANKER_MAX_TOKENS_PER_CANDIDATE", "128")
	env.comment("Stable worker id: tasks in flight survive a container recreate.")
	env.plain("HINDSIGHT_API_WORKER_ID", "backsight-"+workerName(host))
	if env.err != nil {
		return Files{}, env.err
	}
	return Files{Compose: compose.Bytes(), Env: env.buf.Bytes()}, nil
}

type envFile struct {
	buf bytes.Buffer
	err error
}

func (e *envFile) comment(s string) { fmt.Fprintf(&e.buf, "# %s\n", s) }

func (e *envFile) plain(k, v string) {
	if strings.ContainsAny(v, " \t\n'\"#$\\") {
		e.fail(k)
		return
	}
	fmt.Fprintf(&e.buf, "%s=%s\n", k, v)
}

// quoted writes a single-quoted value: Compose takes it literally.
func (e *envFile) quoted(k, v string) {
	if strings.ContainsAny(v, "'\n\r") {
		e.fail(k)
		return
	}
	fmt.Fprintf(&e.buf, "%s='%s'\n", k, v)
}

func (e *envFile) fail(k string) {
	if e.err == nil {
		e.err = fmt.Errorf("%s: the value contains a quote, newline or shell character that .env cannot carry", k)
	}
}

var nonWord = regexp.MustCompile(`[^a-z0-9]+`)

func workerName(host string) string {
	n := strings.Trim(nonWord.ReplaceAllString(strings.ToLower(host), "-"), "-")
	if n == "" {
		return "host"
	}
	return n
}

// Changes says which rendered files differ from what is on disk.
type Changes struct {
	Compose bool `json:"compose_changed"`
	Env     bool `json:"env_changed"`
}

// Diff compares f with the files in dir without writing.
func Diff(dir string, f Files) (Changes, error) {
	var c Changes
	var err error
	if c.Compose, err = differs(filepath.Join(dir, "compose.yaml"), f.Compose); err != nil {
		return c, err
	}
	c.Env, err = differs(filepath.Join(dir, ".env"), f.Env)
	return c, err
}

// Write puts f in dir (compose.yaml 0644, .env 0600), only where it changed.
func Write(dir string, f Files) (Changes, error) {
	c, err := Diff(dir, f)
	if err != nil {
		return c, err
	}
	if c.Compose {
		if err := fsutil.WriteAtomic(filepath.Join(dir, "compose.yaml"), f.Compose, 0o644); err != nil {
			return c, err
		}
	}
	env := filepath.Join(dir, ".env")
	if c.Env {
		if err := fsutil.WriteAtomic(env, f.Env, 0o600); err != nil {
			return c, err
		}
	} else if fi, err := os.Stat(env); err == nil && fi.Mode().Perm() != 0o600 {
		if err := os.Chmod(env, 0o600); err != nil { // loosened by hand: it holds secrets
			return c, err
		}
	}
	return c, nil
}

func differs(path string, want []byte) (bool, error) {
	got, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return true, nil
	}
	if err != nil {
		return false, err
	}
	return !bytes.Equal(got, want), nil
}

// Redact replaces every known secret value in text, for error messages that
// quote Docker or provider output.
func Redact(text string, sec config.Secrets) string {
	for _, v := range []string{sec.APIKey, sec.UIKey, sec.DBPassword, sec.LLMAPIKey, sec.BackupIdentity} {
		if len(v) >= 6 {
			text = strings.ReplaceAll(text, v, "[redacted]")
		}
	}
	return text
}
