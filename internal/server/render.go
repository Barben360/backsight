// HindsightImage is the pinned Hindsight image. init sets it after the
// linker, so -X cannot change it; a testhooks build may pin another (CI's
// update proof), and a release has no such tag (make verify-keys).
var HindsightImage string

func init() {
	HindsightImage = pinnedHindsight
	if t := testImage(); t != "" {
		HindsightImage = t
	}
}

// PinnedVersion is the tag of HindsightImage ("1.1.0"): the Hindsight
// version this backsight is built for.
func PinnedVersion() string {
	ref, _, _ := strings.Cut(HindsightImage, "@")
	if i := strings.LastIndex(ref, ":"); i >= 0 {
		return ref[i+1:]
	}
	return ref
}

const pinnedHindsight = "ghcr.io/vectorize-io/hindsight:1.1.0@sha256:50311d02b4d5d2b7c5242bd336edf8735df8374eaad496a92f49c83b37d2aa06"

// Files are the rendered server: Docker's compose project, or the native
// runtime's environment and units.
type Files struct {
	Compose []byte
	Env     []byte
	// Units maps a systemd unit file's base name to its content (native);
	// nil on Docker.
	Units map[string][]byte
}

// MissingSecretsError lists the secrets render needs and does not have.
type MissingSecretsError struct{ Names []string }

func (e *MissingSecretsError) Error() string {
	cmds := make([]string, len(e.Names))
	for i, n := range e.Names {
		cmds[i] = "backsight secret set " + n
	}
	return "missing secrets: " + strings.Join(e.Names, ", ") + "; run " + strings.Join(cmds, ", then ")
}

