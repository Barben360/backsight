// Render builds compose.yaml and .env for cfg; host names the worker.
func Render(cfg config.Config, sec config.Secrets, host string) (Files, error) {
	return RenderImage(cfg, sec, host, ImageFor(cfg))
}

// RenderImage is Render with the Hindsight image given: an upgrade's
// rollback renders the image the server ran before.
func RenderImage(cfg config.Config, sec config.Secrets, host, image string) (Files, error) {
	if err := checkRenderable(cfg, sec); err != nil {
		return Files{}, err
	}

	apiPort, err := cfg.APIPort()
	if err != nil {
		return Files{}, err
	}
	// Loopback is always published: the host's own client keeps server.url
	// on 127.0.0.1 when the server is opened to other PCs.
	binds := []string{"127.0.0.1"}
	if cfg.Network.Exposure == "private" {
		bind := cfg.Network.BindIP
		if strings.Contains(bind, ":") { // IPv6: Compose wants [addr]:port
			bind = "[" + bind + "]"
		}
		binds = append(binds, bind)
	}
	var compose bytes.Buffer
	project := cfg.Server.Project
	if project == "" {
		project = Project
	}
	if err := composeTmpl.Execute(&compose, map[string]any{"Project": project, "Postgres": PostgresImage, "Hindsight": image,
		"Binds": binds, "APIPort": apiPort, "UIPort": cfg.Server.UIPort}); err != nil {
		return Files{}, err
	}

	env := &envFile{}
	env.comment(envHeader)
	dsn := url.URL{Scheme: "postgresql", User: url.UserPassword("hindsight", sec.DBPassword), Host: "db:5432", Path: "/hindsight"}
	hindsightEnv(env, cfg, sec, host, dsn.String(), true)
	if env.err != nil {
		return Files{}, env.err
	}
	return Files{Compose: compose.Bytes(), Env: env.buf.Bytes()}, nil
}

// envHeader opens the server's environment file.
const envHeader = "Generated by backsight: holds secrets (mode 0600). Do not edit; run backsight server render."

// hindsightEnv writes Hindsight's settings, the same for both runtimes and
// in Docker's order, dsn being the database's URL. docker adds what only
// Docker's .env holds: the database password Compose gives Postgres, the
// control plane's keys and the torch reranker; the native runtime gets
// the onnx reranker instead (decision 0078 requirement 8, ruling R7).
func hindsightEnv(env *envFile, cfg config.Config, sec config.Secrets, host, dsn string, docker bool) {
	if docker {
		env.quoted("BACKSIGHT_DB_PASSWORD", sec.DBPassword)
	}
	env.quoted("HINDSIGHT_API_DATABASE_URL", dsn)
	env.plain("HINDSIGHT_API_TENANT_EXTENSION", "hindsight_api.extensions.builtin.tenant:ApiKeyTenantExtension")
	env.quoted("HINDSIGHT_API_TENANT_API_KEY", sec.APIKey)
	if docker {
		env.quoted("HINDSIGHT_CP_DATAPLANE_API_KEY", sec.APIKey)
		env.quoted("HINDSIGHT_CP_ACCESS_KEY", sec.UIKey)
	}
	env.plain("HINDSIGHT_API_LLM_PROVIDER", cfg.LLM.Provider)
	env.plain("HINDSIGHT_API_LLM_MODEL", cfg.LLM.Model)
	if sec.LLMAPIKey != "" {
		env.quoted("HINDSIGHT_API_LLM_API_KEY", sec.LLMAPIKey)
	}
	if cfg.LLM.BaseURL != "" {
		env.quoted("HINDSIGHT_API_LLM_BASE_URL", cfg.LLM.BaseURL)
	}
	env.plain("HINDSIGHT_API_LLM_TIMEOUT", "300")
	env.comment("Facts, observations and reflect answers always in English, whatever language you write in: English facts are recalled better.")
	env.plain("HINDSIGHT_API_LLM_OUTPUT_LANGUAGE", "English")
	env.comment("Multilingual preset: multilingual-e5-small (onnx default) + mmarco reranker.")
	env.comment("On CPU reranking is ~98 % of a recall: 30 candidates of at most 128 tokens keep the prompt hook p95 under 2.5 s.")
	env.plain("HINDSIGHT_API_EMBEDDINGS_PROVIDER", "onnx")
	if docker {
		env.plain("HINDSIGHT_API_RERANKER_PROVIDER", "local")
		env.plain("HINDSIGHT_API_RERANKER_LOCAL_MODEL", RerankerModel)
		env.plain("HINDSIGHT_API_RERANKER_LOCAL_BUCKET_BATCHING", "true")
	} else {
		env.plain("HINDSIGHT_API_RERANKER_PROVIDER", "onnx")
		env.plain("HINDSIGHT_API_RERANKER_ONNX_MODEL_ID", RerankerModel)
	}
	env.plain("HINDSIGHT_API_RERANKER_MAX_CANDIDATES", "30")
	env.plain("HINDSIGHT_API_RERANKER_MAX_TOKENS_PER_CANDIDATE", "128")
	env.comment("LLM request log: token rows kept 30 days for stats and the backfill budget; no prompt or memory text stored.")
	env.plain("HINDSIGHT_API_LLM_TRACE_RETENTION_DAYS", "30")
	env.plain("HINDSIGHT_API_LLM_TRACE_MAX_CHARS", "1")
	env.comment("Stable worker id: tasks in flight survive a container recreate.")
	env.plain("HINDSIGHT_API_WORKER_ID", "backsight-"+workerName(host))
}

// RerankerModel is the multilingual preset's reranker, torch on Docker and
// onnx on the native runtime.
const RerankerModel = "cross-encoder/mmarco-mMiniLMv2-L12-H384-v1"

type envFile struct {
	buf bytes.Buffer
	err error
}

func (e *envFile) comment(s string) { fmt.Fprintf(&e.buf, "# %s\n", s) }

func (e *envFile) plain(k, v string) {
	if strings.ContainsAny(v, " \t\n'\"#$\\") {
		e.fail(k)
		return
	}
	fmt.Fprintf(&e.buf, "%s=%s\n", k, v)
}

// quoted writes a single-quoted value: Compose takes it literally.
func (e *envFile) quoted(k, v string) {
	if strings.ContainsAny(v, "'\n\r") {
		e.fail(k)
		return
	}
	fmt.Fprintf(&e.buf, "%s='%s'\n", k, v)
}

func (e *envFile) fail(k string) {
	if e.err == nil {
		e.err = fmt.Errorf("%s: the value contains a quote, newline or shell character that .env cannot carry", k)
	}
}

// keptEnvKeys maps the .env variables Render writes the server keys to
// onto their secrets.toml names.
var keptEnvKeys = map[string]string{
	"BACKSIGHT_DB_PASSWORD":        "db_password",
	"HINDSIGHT_API_TENANT_API_KEY": "api_key",
	"HINDSIGHT_CP_ACCESS_KEY":      "ui_key",
}

// KeptSecrets reads the server keys (db_password, api_key, ui_key) from a
// .env Render wrote in dir and an uninstall --purge-local kept: setting
// up again adopts them, so the kept database and its clients' key still
// work (M5 review rules, "Setting up again over kept data"). The quotes
// quoted() adds are stripped; an absent file gives none.
func KeptSecrets(dir string) (map[string]string, error) {
	return KeptSecretsIn(filepath.Join(dir, ".env"))
}

// KeptSecretsIn is KeptSecrets of the environment file a runtime wrote
// (its SecretFiles): Docker's .env, or the native server.env, which holds
// the database password only in the database's URL and has no UI key.
func KeptSecretsIn(file string) (map[string]string, error) {
	raw, err := os.ReadFile(file)
	if errors.Is(err, fs.ErrNotExist) {
		return map[string]string{}, nil
	}
	if err != nil {
		return nil, err
	}
	out := map[string]string{}
	dsn := ""
	for _, line := range strings.Split(string(raw), "\n") {
		k, v, ok := strings.Cut(strings.TrimSpace(strings.TrimSuffix(line, "\r")), "=")
		if len(v) >= 2 && v[0] == v[len(v)-1] && (v[0] == '\'' || v[0] == '"') {
			v = v[1 : len(v)-1]
		}
		if ok && k == "HINDSIGHT_API_DATABASE_URL" {
			dsn = v
		}
		name, known := keptEnvKeys[k]
		if !ok || !known {
			continue
		}
		if v != "" {
			out[name] = v
		}
	}
	if _, ok := out["db_password"]; !ok && dsn != "" {
		if u, err := url.Parse(dsn); err == nil && u.User != nil {
			if pw, set := u.User.Password(); set && pw != "" {
				out["db_password"] = pw
			}
		}
	}
	return out, nil
}

var nonWord = regexp.MustCompile(`[^a-z0-9]+`)

func workerName(host string) string {
	n := strings.Trim(nonWord.ReplaceAllString(strings.ToLower(host), "-"), "-")
	if n == "" {
		return "host"
	}
	return n
}

// Changes says which rendered files differ from what is on disk.
type Changes struct {
	Compose bool `json:"compose_changed"`
	Env     bool `json:"env_changed"`
	// Units: a unit file changed (native only, never reported on Docker).
	Units bool `json:"units_changed,omitempty"`
}

// Diff compares f with the files in dir without writing.
func Diff(dir string, f Files) (Changes, error) {
	var c Changes
	var err error
	if c.Compose, err = differs(filepath.Join(dir, "compose.yaml"), f.Compose); err != nil {
		return c, err
	}
	c.Env, err = differs(filepath.Join(dir, ".env"), f.Env)
	return c, err
}

// Write puts f in dir (compose.yaml 0644, .env 0600), only where it changed.
func Write(dir string, f Files) (Changes, error) {
	c, err := Diff(dir, f)
	if err != nil {
		return c, err
	}
	if c.Compose {
		if err := fsutil.WriteAtomic(filepath.Join(dir, "compose.yaml"), f.Compose, 0o644); err != nil {
			return c, err
		}
	}
	env := filepath.Join(dir, ".env")
	if c.Env {
		if err := fsutil.WriteAtomic(env, f.Env, 0o600); err != nil {
			return c, err
		}
	} else if fi, err := os.Stat(env); err == nil && fi.Mode().Perm() != 0o600 {
		if err := os.Chmod(env, 0o600); err != nil { // loosened by hand: it holds secrets
			return c, err
		}
	}
	return c, nil
}

func differs(path string, want []byte) (bool, error) {
	got, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return true, nil
	}
	if err != nil {
		return false, err
	}
	return !bytes.Equal(got, want), nil
}

// Redact replaces every known secret value in text, for error messages that
// quote Docker or provider output.
func Redact(text string, sec config.Secrets) string {
	for _, v := range []string{sec.APIKey, sec.UIKey, sec.DBPassword, sec.LLMAPIKey, sec.BackupIdentity} {
		if len(v) >= 6 {
			text = strings.ReplaceAll(text, v, "[redacted]")
		}
	}
	return text
}

// ImageFor is the Hindsight image the install runs: the pinned one, or the
// digest config sets.
func ImageFor(cfg config.Config) string {
	if cfg.Server.Digest != "" {
		return "ghcr.io/vectorize-io/hindsight@" + cfg.Server.Digest
	}
	return HindsightImage
}

// CompareImages orders two Hindsight image references, by digest (the same
// digest is the same image) or else by their version tags; comparable is
// false when neither tells (a digest alone, a pre-release tag).
func CompareImages(a, b string) (cmp int, comparable bool) {
	digest := func(ref string) string { _, d, _ := strings.Cut(ref, "@"); return d }
	if a != "" && (a == b || (digest(a) != "" && digest(a) == digest(b))) {
		return 0, true
	}
	va, okA := imageVersion(a)
	vb, okB := imageVersion(b)
	if !okA || !okB {
		return 0, false
	}
	for i := range va {
		if va[i] != vb[i] {
			if va[i] < vb[i] {
				return -1, true
			}
			return 1, true
		}
	}
	return 0, false // same version, different digests: a rebuild
}

// releaseTag is a release's version; nativeTag a native install's,
// <hindsight version>-<the lock's hash, 12 hex digits>.
var (
	releaseTag = regexp.MustCompile(`^v?([0-9]+\.[0-9]+\.[0-9]+)$`)
	nativeTag  = regexp.MustCompile(`^([0-9]+\.[0-9]+\.[0-9]+)-[0-9a-f]{12}$`)
)

// HindsightVersionOf is the Hindsight release ("1.1.0") an image reference
// tags or a native version starts with; "" when it names none (a digest
// alone, a pre-release).
func HindsightVersionOf(ref string) string {
	name, _, _ := strings.Cut(ref, "@")
	tag := name
	if i := strings.LastIndex(name, ":"); i >= 0 && !strings.Contains(name[i:], "/") {
		tag = name[i+1:]
	} else if strings.Contains(name, "/") {
		return "" // an image without a tag (a registry's port is none)
	}
	for _, re := range []*regexp.Regexp{releaseTag, nativeTag} {
		if m := re.FindStringSubmatch(tag); m != nil {
			return m[1]
		}
	}
	return ""
}

// CompareHindsight orders two Hindsight releases ("1.1.0"), what restore
// compares across runtimes; comparable is false when either is none.
func CompareHindsight(a, b string) (cmp int, comparable bool) {
	va, okA := imageVersion(":" + a)
	vb, okB := imageVersion(":" + b)
	if !okA || !okB || a == "" || b == "" {
		return 0, false
	}
	for i := range va {
		if va[i] != vb[i] {
			if va[i] < vb[i] {
				return -1, true
			}
			return 1, true
		}
	}
	return 0, true
}

// imageVersion reads the x.y.z tag of an image reference.
func imageVersion(ref string) ([3]int, bool) {
	var v [3]int
	name, _, _ := strings.Cut(ref, "@")
	i := strings.LastIndex(name, ":")
	if i < 0 || strings.Contains(name[i:], "/") {
		return v, false
	}
	parts := strings.Split(strings.TrimPrefix(name[i+1:], "v"), ".")
	if len(parts) != 3 {
		return v, false
	}
	for j, p := range parts {
		n, err := strconv.Atoi(p)
		if err != nil || n < 0 {
			return v, false
		}
		v[j] = n
	}
	return v, true
}

