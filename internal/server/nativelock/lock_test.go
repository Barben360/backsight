// withLock makes Requirements raw for the test.
func withLock(t *testing.T, raw string) {
	t.Helper()
	old := Requirements
	Requirements = []byte(raw)
	t.Cleanup(func() { Requirements = old })
}

const sampleLock = `# Generated by scripts/native-lock.sh: do not edit.
# image: ghcr.io/vectorize-io/hindsight:9.8.7@sha256:abc
# python: 3.11.16 (image: 3.11.17)
# platform: x86_64-manylinux_2_28
Hindsight_API.Slim==9.8.7 \
    --hash=sha256:1111111111111111111111111111111111111111111111111111111111111111
pg0-embedded==0.15.2 \
    --hash=sha256:2222222222222222222222222222222222222222222222222222222222222222 \
    --hash=sha256:3333333333333333333333333333333333333333333333333333333333333333
zope.interface==7.0 ; python_full_version >= '3.11' \
    --hash=sha256:4444444444444444444444444444444444444444444444444444444444444444
`

func TestNativeLockReadsItsHeaderAndVersions(t *testing.T) {
	withLock(t, sampleLock)
	p := For("linux")
	if got := p.Image(); got != "ghcr.io/vectorize-io/hindsight:9.8.7@sha256:abc" {
		t.Errorf("Image() = %q", got)
	}
	if got := p.Python(); got != "3.11.16" {
		t.Errorf("Python() = %q, want the header's own patch, not the image's", got)
	}
	if got := p.Hindsight(); got != "9.8.7" {
		t.Errorf("Hindsight() = %q, want hindsight-api-slim's version (name normalised)", got)
	}
	want := map[string]string{"hindsight-api-slim": "9.8.7", "pg0-embedded": "0.15.2", "zope-interface": "7.0"}
	got := p.Versions()
	if len(got) != len(want) {
		t.Errorf("Versions() = %v, want %v", got, want)
	}
	for k, v := range want {
		if got[k] != v {
			t.Errorf("Versions()[%q] = %q, want %q (all: %v)", k, got[k], v, got)
		}
	}
	sum := sha256.Sum256([]byte(sampleLock))
	if h := p.Hash12(); h != hex.EncodeToString(sum[:])[:12] {
		t.Errorf("Hash12() = %q, want the first 12 hex digits of the lock's sha256", h)
	}
	withLock(t, sampleLock+"# one more comment\n")
	if For("linux").Hash12() == hex.EncodeToString(sum[:])[:12] {
		t.Error("Hash12() did not change with the lock's bytes")
	}
}

// The embedded lock is what scripts/native-lock.sh writes: its header,
// Python at the image's own patch (decision 0078 requirement 4, ruling
// R24: uv 0.13.1 provides 3.11.17), every requirement hash-pinned,
// pg0-embedded 0.15.2 and no torch. The comparison with the server's
// pinned image lives in package server (TestNativeLockMatchesThePin):
// this package never imports server (ruling R8).
func TestNativeLockIsTheGeneratedOne(t *testing.T) {
	p := For("linux")
	lines := strings.Split(string(Requirements), "\n")
	if len(lines) < 5 || lines[0] != "# Generated by scripts/native-lock.sh: do not edit." ||
		!strings.HasPrefix(lines[1], "# image: ") || !strings.HasPrefix(lines[2], "# python: ") ||
		lines[3] != "# platform: x86_64-manylinux_2_28" {
		t.Fatalf("the lock's header is not native-lock.sh's:\n%s", strings.Join(lines[:min(5, len(lines))], "\n"))
	}
	if !regexp.MustCompile(`^3\.11\.[0-9]+$`).MatchString(p.Python()) {
		t.Errorf("Python() = %q, want 3.11.<patch>", p.Python())
	}
	if want := "# python: " + p.Python() + " (image: 3.11.17)"; lines[2] != want || p.Python() != "3.11.17" {
		t.Errorf("python header %q: want %q, the image's own patch (R24)", lines[2], want)
	}
	v := p.Versions()
	if v["pg0-embedded"] != PG0 || PG0 != "0.15.2" {
		t.Errorf("pg0-embedded = %q, want %s", v["pg0-embedded"], PG0)
	}
	if _, ok := v["torch"]; ok {
		t.Error("the lock holds torch: the image's CPU torch is dropped (onnx only)")
	}
	if v["hindsight-api-slim"] == "" || p.Hindsight() != v["hindsight-api-slim"] {
		t.Errorf("hindsight-api-slim missing from the lock: p.Hindsight() = %q", p.Hindsight())
	}
	if len(v) < 100 {
		t.Errorf("the lock names %d packages: the image's set is about 200", len(v))
	}
	for _, req := range requirementLines(p.Requirements) {
		if !strings.Contains(req, "--hash=sha256:") {
			t.Errorf("requirement without a hash: %s", req)
		}
	}
	if !regexp.MustCompile(`^[0-9a-f]{64}$`).MatchString(UVSHA256) {
		t.Errorf("UVSHA256 = %q, want 64 lowercase hex", UVSHA256)
	}
	if UVVersion != "0.13.1" || UVSHA256 != "eadd9d27c134ab5ac1ffd4473b97a741407f3ea238288f03121fc4deddf90220" {
		t.Errorf("uv pin = %s %s, want Task 1's C6 measure (ruling R24)", UVVersion, UVSHA256)
	}
	if UVAsset != "uv-x86_64-unknown-linux-gnu.tar.gz" {
		t.Errorf("UVAsset = %q", UVAsset)
	}
}

// The Linux lock and the version id derived from it were recorded at
// 884c942 (M7 block 2, Task 2): the Windows lock is another file, and
// nothing may move the Linux one. A deliberate lock bump changes both
// literals in the same commit.
func TestLinuxLockUnchanged(t *testing.T) {
	const wantSHA = "82e13826d426d3f2ed5f29466b905395dd2e6543a27891a3029f2fd9d97409f6"
	const wantHash12 = "82e13826d426"
	sum := sha256.Sum256(Requirements)
	if got := hex.EncodeToString(sum[:]); got != wantSHA {
		t.Errorf("requirements-linux-amd64.txt sha256 %s, want %s", got, wantSHA)
	}
	if got := For("linux").Hash12(); got != wantHash12 {
		t.Errorf("Hash12 %s, want %s", got, wantHash12)
	}
	if got := For("linux").Hindsight() + "-" + For("linux").Hash12(); got != "1.1.0-"+wantHash12 {
		t.Errorf("native version id %s", got)
	}
}

// shared lists the package names of a lock with their versions, from its
// requirement lines.
func lockVersions(t *testing.T, p Platform) map[string]string {
	t.Helper()
	v := p.Versions()
	if len(v) < 100 {
		t.Fatalf("%s lock names %d packages", p.GOOS, len(v))
	}
	return v
}

// windowsOnly are the packages only the Windows lock holds (scripts/native-lock.sh's
// WINDOWS_ONLY); windowsExceptions are shared packages allowed another
// version there, each with its reason (WINDOWS_EXCEPTIONS: none today).
var (
	windowsOnly       = map[string]bool{"msvc-runtime": true, "winloop": true, "colorama": true, "tzdata": true, "pywin32": true, "pywin32-ctypes": true}
	windowsExceptions = map[string]string{}
)

// checkShared reports each package of win that is shared with lin under
// another version and not excepted, or only in win and not in only.
func checkShared(lin, win map[string]string, only map[string]bool, exceptions map[string]string) (bad []string) {
	for name, wv := range win {
		lv, shared := lin[name]
		switch {
		case shared && lv != wv:
			if _, ok := exceptions[name]; !ok {
				bad = append(bad, name+": Linux "+lv+", Windows "+wv)
			}
		case !shared && !only[name]:
			bad = append(bad, name+"=="+wv+": only in the Windows lock")
		}
	}
	return bad
}

func TestWindowsLockSharesLinuxVersions(t *testing.T) {
	lin, win := lockVersions(t, For("linux")), lockVersions(t, For("windows"))
	if bad := checkShared(lin, win, windowsOnly, windowsExceptions); len(bad) > 0 {
		t.Errorf("the Windows lock strays from the Linux lock:\n  %s", strings.Join(bad, "\n  "))
	}
	for name := range windowsOnly {
		if _, ok := win[name]; !ok {
			t.Errorf("windowsOnly names %s, which the Windows lock lacks", name)
		}
	}
	if win["msvc-runtime"] != "14.44.35112" {
		t.Errorf("msvc-runtime = %q, want 14.44.35112 (E34 W3)", win["msvc-runtime"])
	}
	if win["hindsight-api-slim"] != "1.1.0" || win["pg0-embedded"] != PG0 {
		t.Errorf("hindsight-api-slim %q, pg0-embedded %q", win["hindsight-api-slim"], win["pg0-embedded"])
	}
	// The checker itself bites: another version, an unlisted Windows-only
	// package, and an exception that excuses.
	l := map[string]string{"a": "1"}
	if bad := checkShared(l, map[string]string{"a": "2"}, nil, nil); len(bad) != 1 {
		t.Errorf("another version not reported: %v", bad)
	}
	if bad := checkShared(l, map[string]string{"a": "1", "b": "1"}, nil, nil); len(bad) != 1 {
		t.Errorf("an unlisted Windows-only package not reported: %v", bad)
	}
	if bad := checkShared(l, map[string]string{"a": "2"}, nil, map[string]string{"a": "why"}); len(bad) != 0 {
		t.Errorf("an exception did not excuse: %v", bad)
	}
}

func TestWindowsLockHashesEveryLine(t *testing.T) {
	win := For("windows")
	lines := strings.Split(string(win.Requirements), "\n")
	want := []string{
		"# Generated by scripts/native-lock.sh --platform windows: do not edit.",
		"# image: " + For("linux").Image(),
		"# python: 3.11.17 (image: 3.11.17)",
		"# platform: x86_64-pc-windows-msvc",
		"# linux-lock: " + For("linux").Hash12(),
	}
	for i, w := range want {
		if lines[i] != w {
			t.Errorf("header line %d = %q, want %q", i+1, lines[i], w)
		}
	}
	if win.Python() != "3.11.17" || win.Hindsight() != "1.1.0" {
		t.Errorf("Python %q, Hindsight %q", win.Python(), win.Hindsight())
	}
	reqs := requirementLines(win.Requirements)
	if len(reqs) != len(win.Versions()) {
		t.Errorf("%d requirement lines, %d versions", len(reqs), len(win.Versions()))
	}
	for _, req := range reqs {
		if !strings.Contains(req, "--hash=sha256:") {
			t.Errorf("requirement without a hash: %s", req)
		}
	}
	if _, ok := win.Versions()["torch"]; ok {
		t.Error("the Windows lock holds torch")
	}
}

func TestForWindowsPicksTheZipAndItsHash(t *testing.T) {
	w := For("windows")
	if w.GOOS != "windows" || w.UVAsset != "uv-x86_64-pc-windows-msvc.zip" ||
		w.UVSHA256 != "3b2661a463a5baea7f5076ea2b25ab71d77f36a6c0d809e5350651792f80a672" {
		t.Errorf("windows platform = %s %s %s", w.GOOS, w.UVAsset, w.UVSHA256)
	}
	if !bytes.Equal(w.Requirements, WindowsRequirements) || bytes.Equal(w.Requirements, For("linux").Requirements) {
		t.Error("windows does not carry its own lock")
	}
	l := For("linux")
	if l.UVAsset != UVAsset || l.UVSHA256 != UVSHA256 || !bytes.Equal(l.Requirements, Requirements) {
		t.Errorf("linux platform = %s %s", l.UVAsset, l.UVSHA256)
	}
	if w.Hash12() == l.Hash12() {
		t.Error("the two locks share a Hash12")
	}
	if got := For("darwin").UVAsset; got != UVAsset {
		t.Errorf("an unknown GOOS gets %s, want the Linux pins", got)
	}
}

// A test lock (TestLock, testhooks builds) stands in for the lock of the
// OS that runs: Windows' own on Windows, where the native chain upgrades
// to a second version from it, the Linux one elsewhere; the other OS's
// lock is left as embedded.
func TestTheTestLockReplacesTheRunningOSsLock(t *testing.T) {
	linux, windows := Requirements, WindowsRequirements
	t.Cleanup(func() { Requirements, WindowsRequirements = linux, windows })
	file := t.TempDir() + "/lock2.txt"
	if err := os.WriteFile(file, []byte(sampleLock), 0o600); err != nil {
		t.Fatal(err)
	}
	applyTestLock("", "windows")
	if !bytes.Equal(Requirements, linux) || !bytes.Equal(WindowsRequirements, windows) {
		t.Fatal("no test lock changed a lock")
	}
	applyTestLock(file, "windows")
	if got := For("windows").Requirements; string(got) != sampleLock {
		t.Errorf("Windows' lock is not the test lock after applyTestLock(windows):\n%.200s", got)
	}
	if !bytes.Equal(Requirements, linux) {
		t.Error("the Linux lock changed for a Windows test lock")
	}
	WindowsRequirements = windows
	applyTestLock(file, "linux")
	if string(For("linux").Requirements) != sampleLock || !bytes.Equal(WindowsRequirements, windows) {
		t.Error("a Linux test lock did not replace the Linux lock alone")
	}
}
