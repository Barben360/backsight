// Package scheduler describes the two OS scheduler entries (decision 0025):
// `jobs tick` every 15 minutes and `jobs maintain` daily, as systemd user
// timers (Linux), launchd agents (macOS) or Task Scheduler tasks (Windows).
// It only builds files and commands; the caller writes the files through
// the config editor (pre-images, undo) and runs the commands.
package scheduler

import (
	"fmt"
	"path/filepath"
	"strings"
)

// Job is one scheduled entry.
type Job struct {
	Name    string // tick | maintain
	Minutes int    // cadence
}

// Jobs are the two entries, in install order.
var Jobs = []Job{{"tick", 15}, {"maintain", 24 * 60}}

// File is a file an entry needs.
type File struct {
	Path    string
	Content string
}

// Plan is what installing (or removing) the entries takes on one system.
type Plan struct {
	Kind     string     `json:"kind"` // systemd | launchd | schtasks
	Files    []File     `json:"-"`
	Activate [][]string `json:"activate"` // commands, after the files are written
	Remove   [][]string `json:"remove"`   // commands, before the files are removed
}

// Paths lists the plan's files.
func (p Plan) Paths() []string {
	out := make([]string, 0, len(p.Files))
	for _, f := range p.Files {
		out = append(out, f.Path)
	}
	return out
}

// For builds the plan for goos. shim is the absolute path of the backsight
// shim; configDir is the user's config directory (XDG_CONFIG_HOME on Linux);
// home is the home directory; uid is the user id (launchd's domain).
func For(goos, shim, home, configDir string, uid int) (Plan, error) {
	switch goos {
	case "linux":
		return systemd(shim, configDir), nil
	case "darwin":
		return launchd(shim, home, uid), nil
	case "windows":
		return schtasks(shim), nil
	}
	return Plan{}, fmt.Errorf("no scheduler support on %s", goos)
}

// UnitName is the systemd unit of job j (without suffix).
func UnitName(j Job) string { return "backsight-" + j.Name }

func systemd(shim, configDir string) Plan {
	dir := filepath.Join(configDir, "systemd", "user")
	p := Plan{Kind: "systemd"}
	var timers []string
	for _, j := range Jobs {
		name := UnitName(j)
		calendar := "*:0/15"
		extra := ""
		if j.Name == "maintain" {
			calendar, extra = "daily", "RandomizedDelaySec=1h\n"
		}
		p.Files = append(p.Files,
			File{filepath.Join(dir, name+".service"), "# Generated by backsight (decision 0025): do not edit.\n[Unit]\nDescription=backsight jobs " + j.Name +
				"\n\n[Service]\nType=oneshot\nExecStart=" + systemdQuote(shim) + " jobs " + j.Name + "\n"},
			File{filepath.Join(dir, name+".timer"), "# Generated by backsight (decision 0025): do not edit.\n[Unit]\nDescription=backsight jobs " + j.Name +
				"\n\n[Timer]\nOnCalendar=" + calendar + "\nPersistent=true\n" + extra + "\n[Install]\nWantedBy=timers.target\n"})
		timers = append(timers, name+".timer")
	}
	p.Activate = [][]string{{"systemctl", "--user", "daemon-reload"}, append([]string{"systemctl", "--user", "enable", "--now"}, timers...)}
	p.Remove = [][]string{append([]string{"systemctl", "--user", "disable", "--now"}, timers...)}
	return p
}

// systemdQuote quotes a path for ExecStart when it holds a space.
func systemdQuote(s string) string {
	if strings.ContainsAny(s, " \t\"\\") {
		return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
	}
	return s
}

// Label is the launchd label of job j.
func Label(j Job) string { return "tech.backsight." + j.Name }

func launchd(shim, home string, uid int) Plan {
	dir := filepath.Join(home, "Library", "LaunchAgents")
	p := Plan{Kind: "launchd"}
	domain := fmt.Sprintf("gui/%d", uid)
	for _, j := range Jobs {
		path := filepath.Join(dir, Label(j)+".plist")
		schedule := "<key>StartInterval</key><integer>900</integer>"
		if j.Name == "maintain" {
			schedule = "<key>StartCalendarInterval</key><dict><key>Hour</key><integer>4</integer><key>Minute</key><integer>0</integer></dict>"
		}
		p.Files = append(p.Files, File{path, `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by backsight (decision 0025): do not edit. -->
<plist version="1.0"><dict>
<key>Label</key><string>` + Label(j) + `</string>
<key>ProgramArguments</key><array><string>` + xmlEscape(shim) + `</string><string>jobs</string><string>` + j.Name + `</string></array>
` + schedule + `
<key>RunAtLoad</key><false/>
</dict></plist>
`})
		// bootout first: bootstrap fails on an agent already loaded
		p.Activate = append(p.Activate, []string{"launchctl", "bootout", domain + "/" + Label(j)}, []string{"launchctl", "bootstrap", domain, path})
		p.Remove = append(p.Remove, []string{"launchctl", "bootout", domain + "/" + Label(j)})
	}
	return p
}

func xmlEscape(s string) string {
	return strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;").Replace(s)
}

// TaskName is the Task Scheduler name of job j.
func TaskName(j Job) string { return `backsight\` + j.Name }

func schtasks(shim string) Plan {
	p := Plan{Kind: "schtasks"}
	for _, j := range Jobs {
		run := `"` + shim + `" jobs ` + j.Name
		sched := []string{"/SC", "MINUTE", "/MO", "15"}
		if j.Name == "maintain" {
			sched = []string{"/SC", "DAILY", "/ST", "04:00"}
		}
		p.Activate = append(p.Activate, append([]string{"schtasks", "/Create", "/F", "/TN", TaskName(j), "/TR", run}, sched...))
		p.Remove = append(p.Remove, []string{"schtasks", "/Delete", "/F", "/TN", TaskName(j)})
	}
	return p
}
