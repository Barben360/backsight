func benchOptions(t testing.TB, stateDir string) Options {
	t.Helper()
	return Options{
		Dirs: paths.Dirs{State: stateDir}, Home: t.TempDir(), Getenv: func(string) string { return "" },
		Now: func() time.Time { return indexgen.Now }, BinaryVersion: "v9.9.9-test",
	}
}

// firstBuild opens a new index over stateDir and ingests everything, with
// no deadline, then checkpoints the WAL into the file (the jobs tick's
// TRUNCATE checkpoint, or the close, would flush it otherwise: up to
// 256 MiB on Windows); it returns the index, left open.
func firstBuild(t testing.TB, stateDir string) *Index {
	t.Helper()
	ix, err := Open(context.Background(), benchOptions(t, stateDir))
	if err != nil {
		t.Fatal(err)
	}
	fr, err := ix.CatchUp(context.Background(), time.Hour)
	if err != nil {
		t.Fatal(err)
	}
	if fr.Partial {
		t.Fatal("the first build is partial")
	}
	if err := ix.Checkpoint(context.Background()); err != nil {
		t.Fatal(err)
	}
	return ix
}

// catchUp15 appends 15 minutes of lines (60 telemetry, 10 journal) to
// stateDir, generated by spec, and runs one catch-up within ViewBudget,
// which must read exactly those 70 lines; it returns the catch-up's time
// (for the benchmark). The ledger is unchanged.
func catchUp15(t testing.TB, ix *Index, stateDir string, spec indexgen.Spec, round int) time.Duration {
	t.Helper()
	indexgen.AppendRecent(t, stateDir, spec, 60, 10, round)
	start := time.Now()
	fr, err := ix.CatchUp(context.Background(), ViewBudget)
	d := time.Since(start)
	if err != nil {
		t.Fatal(err)
	}
	if fr.Partial || fr.Lines != 70 {
		t.Fatalf("catch-up: partial=%v lines=%d, want a complete one of 70", fr.Partial, fr.Lines)
	}
	return d
}

// ingestSpec is the history TestIndexIngestsAGeneratedHistory builds: two
// months of every kind of line, small enough for -race. The benchmarks
// run on indexgen.Budget.
var ingestSpec = indexgen.Spec{Months: 2, TelemetryPerYear: 30_000, JournalPerYear: 3_000, Memories: 500, Seed: 1, Collection: true}

// TestIndexIngestsAGeneratedHistory: a first build of a generated
// history lands every kind and fails no line; each 15-minute catch-up
// after it reads exactly its new lines, not the history again; and a
// catch-up with nothing new reads the ledger only when its stamp changed.
// What these take is BenchmarkFirstBuild's and BenchmarkCatchUp15Minutes'
// (go test -bench), never a test's.
func TestIndexIngestsAGeneratedHistory(t *testing.T) {
	state := t.TempDir()
	indexgen.Generate(t, state, ingestSpec)
	ix := firstBuild(t, state)
	defer func() { _ = ix.Close() }()
	for round := range 3 {
		catchUp15(t, ix, state, ingestSpec, round)
	}
	// every kind landed and no line failed (the spec gives about 1540
	// prompts, 1160 tools and 990 shows)
	var errs, prompts, tools, shows, ledger int
	if err := ix.ReadTx(context.Background(), func(tx *sql.Tx) error {
		for q, p := range map[string]*int{
			"ingest_errors": &errs, "tel_prompt": &prompts, "tel_tool": &tools, "shows": &shows, "ledger": &ledger,
		} {
			if err := tx.QueryRow("SELECT count(*) FROM " + q).Scan(p); err != nil {
				return err
			}
		}
		return nil
	}); err != nil {
		t.Fatal(err)
	}
	if errs != 0 || prompts < 1000 || tools < 750 || shows < 650 || ledger != ingestSpec.Memories {
		t.Errorf("generated state not fully ingested: %d errors, %d prompts, %d tools, %d shows, %d ledger rows", errs, prompts, tools, shows, ledger)
	}
	ledgerSkips(t, state, 5)
}

// countedCurrent is the feedback directory's CurrentReader, its reads
// counted; its Stamp is CurrentReader's.
type countedCurrent struct {
	feedback.CurrentReader
	alls atomic.Int64
}

func (c *countedCurrent) All() (feedback.Ledger, error) {
	c.alls.Add(1)
	return c.CurrentReader.All()
}

// stampless is a CurrentReader with its Stamp hidden, its reads counted.
type stampless struct {
	r    feedback.CurrentReader
	alls atomic.Int64
}

func (s *stampless) All() (feedback.Ledger, error) {
	s.alls.Add(1)
	return s.r.All()
}

// ledgerSkips checks what the ledger's skip saves: the feedback files
// aged an hour before the clock, n catch-ups with nothing new on two
// handles of stateDir's index, one reading through the CurrentReader (it
// reads once, then skips on its Stamp), one through the same reader
// without its Stamp (it reads every time).
func ledgerSkips(t *testing.T, stateDir string, n int) {
	t.Helper()
	ctx := context.Background()
	fdir := paths.Dirs{State: stateDir}.FeedbackDir()
	ents, err := os.ReadDir(fdir)
	if err != nil {
		t.Fatal(err)
	}
	aged := indexgen.Now.Add(-time.Hour)
	for _, e := range ents {
		if err := os.Chtimes(filepath.Join(fdir, e.Name()), aged, aged); err != nil {
			t.Fatal(err)
		}
	}
	open := func(r LedgerSource) *Index {
		o := benchOptions(t, stateDir)
		o.Ledger = r
		ix, err := Open(ctx, o)
		if err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() { _ = ix.Close() })
		return ix
	}
	skipR := &countedCurrent{CurrentReader: feedback.CurrentReader{Dir: fdir}}
	fullR := &stampless{r: feedback.CurrentReader{Dir: fdir}}
	skipIx, fullIx := open(skipR), open(fullR)
	if !skipIx.localFeedback {
		t.Logf("ledger skip: the feedback directory is not local here (%v), not checked", detectFS(fdir, "", func(string) string { return "" }))
		return
	}
	run := func(ix *Index) {
		if fr, err := ix.CatchUp(ctx, ViewBudget); err != nil || fr.Partial {
			t.Fatalf("catch-up: %v, partial %v", err, fr.Partial)
		}
	}
	run(skipIx) // records the stamp
	run(fullIx)
	for range n {
		run(skipIx)
		run(fullIx)
	}
	if got := skipR.alls.Load(); got != 1 {
		t.Errorf("the stamped reader was read %d times, want once", got)
	}
	if got := fullR.alls.Load(); got != int64(n+1) {
		t.Errorf("the reader without a stamp was read %d times, want %d", got, n+1)
	}
}

// BenchmarkFirstBuild and BenchmarkCatchUp15Minutes time the index on
// indexgen.Budget, 13 months above a year of the author's PC (go test
// -run '^$' -bench . ./internal/index/). The plan's limits (a first
// build within 60 s, a 15-minute catch-up within 600 ms: 3x the author's
// measures) are checked there by hand: no test holds the index to a time.
func BenchmarkFirstBuild(b *testing.B) {
	state := b.TempDir()
	indexgen.Generate(b, state, indexgen.Budget)
	for i := 0; i < b.N; i++ {
		b.StopTimer()
		clean(b, state)
		b.StartTimer()
		ix := firstBuild(b, state)
		b.StopTimer()
		_ = ix.Close()
	}
}

func BenchmarkCatchUp15Minutes(b *testing.B) {
	state := b.TempDir()
	indexgen.Generate(b, state, indexgen.Budget)
	ix := firstBuild(b, state)
	defer func() { _ = ix.Close() }()
	var total time.Duration
	for i := 0; i < b.N; i++ {
		total += catchUp15(b, ix, state, indexgen.Budget, i)
	}
	b.ReportMetric(float64(total.Nanoseconds())/float64(b.N), "ns/catchup")
}

// clean removes the index of stateDir, for the next first build.
func clean(b testing.TB, stateDir string) {
	b.Helper()
	if err := os.RemoveAll(paths.Dirs{State: stateDir}.IndexDir()); err != nil {
		b.Fatal(err)
	}
}
